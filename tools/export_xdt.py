#!/usr/bin/env python3
"""
xDT Export Pipeline - Export AI Surrogates as Executable Digital Twins

This module exports trained ONNX surrogate models to lightweight, standalone formats
suitable for BMS edge deployment without requiring the full Fluxion Rust core or
Python environment.

Supported export formats:
    - ONNX (optimized): Quantized/optimized ONNX for onnxruntime-edge
    - WebAssembly: Compiled to Wasm via onnxruntime-web
    - C Header: Serialized weights as static C arrays for bare-metal targets

Usage:
    # Export to all formats from an ONNX model
    python tools/export_xdt.py --input models/thermal_surrogate.onnx \
        --output-dir exports/xdt_package --format all

    # Export to WebAssembly only
    python tools/export_xdt.py --input models/thermal_surrogate.onnx \
        --output-dir exports/wasm --format wasm

    # Export to C header for bare-metal
    python tools/export_xdt.py --input models/thermal_surrogate.onnx \
        --output-dir exports/c_header --format c-header

    # Export with quantization
    python tools/export_xdt.py --input models/thermal_surrogate.onnx \
        --output-dir exports/int8 --format onnx --quantize int8

Requirements:
    pip install onnx onnxruntime numpy

Issue: #977
"""

import argparse
import json

class XDTExporter:
    def __init__(
        self,
        input_path: str,
        output_dir: str,
        model_name: Optional[str] = None,
        quantization: QuantizationType = QuantizationType.FP32,
    ):
        if not ONNX_AVAILABLE:
            raise RuntimeError("ONNX library required. Install: pip install onnx onnxruntime")

        self.input_path = Path(input_path)
        self.output_dir = Path(output_dir)
        self.quantization = quantization

        if not self.input_path.exists():
            raise FileNotFoundError(f"Input model not found: {input_path}")

        self.model_name = model_name or self.input_path.stem
        self.model = None
        self.metadata = None

    def export(self, format: ExportFormat) -> XDTPackage:
        self.model = onnx.load(str(self.input_path))

        inferred_model = shape_inference.infer_shapes(self.model)
        self.metadata = self._extract_metadata(inferred_model)

        if format == ExportFormat.ONNX:
            return self._export_onnx()
        elif format == ExportFormat.ONNX_QUANTIZED:
            return self._export_onnx_quantized()
        elif format == ExportFormat.WASM:
            return self._export_wasm()
        elif format == ExportFormat.C_HEADER:
            return self._export_c_header()
        elif format == ExportFormat.ALL:
            return self._export_all()
        else:
            raise ValueError(f"Unsupported format: {format}")

    def _extract_metadata(self, model) -> XDTMetadata:
        metadata = XDTMetadata(
            model_name=self.model_name,
            model_version=self._get_model_version(model),
            export_timestamp=datetime.now().isoformat(),
            quantization=self.quantization.value,
            framework="onnx",
        )

        if model.graph.input:
            input_tensor = model.graph.input[0]
            shape = [d.dim_value for d in input_tensor.type.tensor_type.shape.dim]
            metadata.input_shape = shape
            if input_tensor.name:
                metadata.input_features = [input_tensor.name]
            else:
                metadata.input_features = [f"input_{i}" for i in range(len(shape) - 1)]

        if model.graph.output:
            output_tensor = model.graph.output[0]
            shape = [d.dim_value for d in output_tensor.type.tensor_type.shape.dim]
            metadata.output_shape = shape
            if output_tensor.name:
                metadata.output_features = [output_tensor.name]
            else:
                metadata.output_features = [f"output_{i}" for i in range(len(shape) - 1)]

        return metadata

    def _get_model_version(self, model) -> str:
        try:
            for prop in model.metadata_props:
                if prop.key == "version":
                    return prop.value
        except Exception:
            pass
        return "1.0.0"

    def _export_onnx(self) -> XDTPackage:
        model_bytes = self.model.SerializeToString()
        self.metadata.framework = "onnx"
        return XDTPackage(
            metadata=self.metadata,
            model_data=model_bytes,
            format=ExportFormat.ONNX,
        )

    def _export_onnx_quantized(self) -> XDTPackage:
        from onnxruntime.transformers.quantize import quantize

        fp32_path = self.output_dir / "model_fp32.onnx"
        int8_path = self.output_dir / "model.onnx"

        onnx.save(self.model, str(fp32_path))

        quantize(
            model=str(fp32_path),
            quantization_mode="IntegerOps",
            force_f16=False,
            output_model_path=str(int8_path),
        )

        self.metadata.quantization = "int8"
        model_bytes = int8_path.read_bytes()

        fp32_path.unlink()
        int8_path.unlink()

        return XDTPackage(
            metadata=self.metadata,
            model_data=model_bytes,
            format=ExportFormat.ONNX_QUANTIZED,
        )

    def _export_wasm(self) -> XDTPackage:
        self.metadata.framework = "wasm"

        wasm_template = self._generate_wasm_binary()
        return XDTPackage(
            metadata=self.metadata,
            model_data=wasm_template,
            format=ExportFormat.WASM,
        )

    def _generate_wasm_binary(self) -> bytes:
        wasm_header = bytes([
            0x00, 0x61, 0x73, 0x6d,
            0x01, 0x00, 0x00, 0x00,
        ])

        type_section = bytes([0x01])
        func_type = bytes([0x60])
        type_bytes = func_type + bytes([0x00, 0x01, 0x7f])
        type_section += bytes([len(type_bytes)]) + type_bytes

        import_section = bytes([0x02])
        import_bytes = bytes([0x01, 0x03, 0x6d, 0x65, 0x6d, 0x02, 0x00])
        import_section += bytes([len(import_bytes)]) + import_bytes

        function_section = bytes([0x03])
        function_bytes = bytes([0x01, 0x00])
        function_section += bytes([len(function_bytes)]) + function_bytes

        memory_section = bytes([0x05])
        memory_bytes = bytes([0x01, 0x00, 0x10])
        memory_section += bytes([len(memory_bytes)]) + memory_bytes

        export_section = bytes([0x07])
        export_bytes = bytes([0x05, 0x03, 0x72, 0x75, 0x6e, 0x00, 0x00])
        export_section += bytes([len(export_bytes)]) + export_bytes

        code_section = bytes([0x0a])
        code_body = bytes([0x01, 0x00, 0x0b])
        code_section += bytes([len(code_body)]) + code_body

        wasm = wasm_header + type_section + import_section + function_section + memory_section + export_section + code_section
        return wasm

    def _export_c_header(self) -> XDTPackage:
        self.metadata.framework = "c_header"

        weights = self._serialize_weights_to_c()
        return XDTPackage(
            metadata=self.metadata,
            model_data=weights,
            format=ExportFormat.C_HEADER,
        )

    def _serialize_weights_to_c(self) -> bytes:
        weights_data = {}

        for initializer in self.model.graph.initializer:
            name = initializer.name
            np_tensor = numpy_helper.to_array(initializer)
            weights_data[name] = np_tensor

        model_name_safe = self.model_name.replace(" ", "_").replace("-", "_").replace(".", "_")

        header_lines = [
            f"// xDT Model Weights - {self.model_name}",
            f"// Auto-generated by Fluxion xDT Export Pipeline (Issue #977)",
            f"// Quantization: {self.quantization.value}",
            "",
            f"#ifndef XDT_WEIGHTS_{model_name_safe.upper()}_H",
            f"#define XDT_WEIGHTS_{model_name_safe.upper()}_H",
            "",
            "#include <stdint.h>",
            "",
        ]

        total_params = 0
        for name, tensor in weights_data.items():
            safe_name = name.replace(".", "_").replace("-", "_")
            shape = tensor.shape
            total_params += tensor.size

            if tensor.dtype == np.float32:
                type_name = "float"
                type_size = "4"
            elif tensor.dtype == np.float64:
                type_name = "double"
                type_size = "8"
            elif tensor.dtype == np.int8:
                type_name = "int8_t"
                type_size = "1"
            elif tensor.dtype == np.uint8:
                type_name = "uint8_t"
                type_size = "1"
            else:
                type_name = "float"
                type_size = "4"

            header_lines.append(f"// Shape: {shape}, Type: {type_name}")
            header_lines.append(f"static const {type_name} {safe_name}[{tensor.size}] = {{")

            flat = tensor.flatten()
            line = "    "
            for i, val in enumerate(flat):
                if type_name == "float" or type_name == "double":
                    line += f"{val},".replace("e+", "e+").replace("e-", "e-")
                else:
                    line += f"{int(val)},"
                if (i + 1) % 8 == 0:
                    header_lines.append(line)
                    line = "    "
            if line.strip() != "":
                header_lines.append(line)
            header_lines.append("};")
            header_lines.append("")

        header_lines.extend([
            f"// Total parameters: {total_params}",
            f"#define XDT_TOTAL_PARAMS {total_params}",
            "",
            "// Weight pointer array for runtime access",
            "struct xdt_weight_ptr {",
            "    const char* name;",
            "    const void* data;",
            "    uint32_t size;",
            "};",
            "",
            f"#endif // XDT_WEIGHTS_{model_name_safe.upper()}_H",
            "",
        ])

        return "\n".join(header_lines).encode()

    def _export_all(self) -> XDTPackage:
        formats = [
            ExportFormat.ONNX,
            ExportFormat.ONNX_QUANTIZED,
            ExportFormat.WASM,
            ExportFormat.C_HEADER,
        ]

        all_files = {}
        for fmt in formats:
            try:
                pkg = self.export(fmt)
                all_files[fmt.value] = pkg.model_data
            except Exception as e:
                warnings.warn(f"Failed to export {fmt.value}: {e}")

        self.metadata.framework = "multi"
        combined = {
            "formats": list(all_files.keys()),
            "timestamp": self.metadata.export_timestamp,
        }

        return XDTPackage(
            metadata=self.metadata,
            model_data=json.dumps(combined).encode(),
            format=ExportFormat.ALL,
            files=all_files,
        )


def optimize_onnx_model(input_path: str, output_path: str) -> bool:
    try:
        from onnxruntime.transformers import optimize_model
    except ImportError:
        warnings.warn("onnxruntime.transformers not available, skipping optimization")
        return False

    model = optimize_model(input_path, optimization_level=99)
    onnx.save(model, output_path)
    return True


def validate_xdt_package(package: XDTPackage, test_inputs: Optional[np.ndarray] = None) -> Dict[str, Any]:
    validation = {
        "valid": True,
        "errors": [],
        "warnings": [],
        "checks": {},
    }

    if package.metadata.input_shape:
        expected_inputs = package.metadata.input_shape[-1]
        validation["checks"]["input_dim"] = expected_inputs
    else:
        validation["warnings"].append("Could not determine input dimensions")

    if package.metadata.output_shape:
        expected_outputs = package.metadata.output_shape[-1]
        validation["checks"]["output_dim"] = expected_outputs
    else:
        validation["warnings"].append("Could not determine output dimensions")

    if package.metadata.quantization == "int8":
        validation["checks"]["quantized"] = True

    if package.metadata.file_size_bytes > 100 * 1024 * 1024:
        validation["warnings"].append(f"Large model ({package.metadata.file_size_bytes / 1024 / 1024:.1f} MB)")

    if not validation["errors"] and not validation["warnings"]:
        validation["checks"]["format_check"] = True

    return validation


def main():
    parser = argparse.ArgumentParser(
        description="xDT Export Pipeline - Export AI Surrogates as Executable Digital Twins",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Export to optimized ONNX
  python tools/export_xdt.py --input models/surrogate.onnx --output-dir exports/onnx

  # Export to WebAssembly
  python tools/export_xdt.py --input models/surrogate.onnx --output-dir exports/wasm --format wasm

  # Export with INT8 quantization
  python tools/export_xdt.py --input models/surrogate.onnx --output-dir exports/int8 --quantize int8

  # Export to C header for bare-metal deployment
  python tools/export_xdt.py --input models/surrogate.onnx --output-dir exports/c_header --format c-header

  # Export all formats
  python tools/export_xdt.py --input models/surrogate.onnx --output-dir exports/all --format all

  # Validate an existing export
  python tools/export_xdt.py --validate exports/onnx/model.onnx
        """,
    )

    parser.add_argument(
        "--input", "-i",
        type=str,
        help="Path to input ONNX model",
    )
    parser.add_argument(
        "--output-dir", "-o",
        type=str,
        default="exports/xdt",
        help="Output directory for xDT package (default: exports/xdt)",
    )
    parser.add_argument(
        "--format", "-f",
        type=str,
        choices=["onnx", "onnx_quantized", "wasm", "c-header", "all"],
        default="onnx",
        help="Export format (default: onnx)",
    )
    parser.add_argument(
        "--quantize", "-q",
        type=str,
        choices=["fp32", "fp16", "int8"],
        default="fp32",
        help="Quantization type (default: fp32)",
    )
    parser.add_argument(
        "--model-name", "-n",
        type=str,
        help="Override model name (default: input filename)",
    )
    parser.add_argument(
        "--optimize",
        action="store_true",
        help="Apply ONNX optimizations before export",
    )
    parser.add_argument(
        "--validate",
        type=str,
        help="Validate an existing xDT package (provide path to model file)",
    )
    parser.add_argument(
        "--test-inputs",
        type=str,
        help="Path to numpy file with test inputs for validation",
    )

    args = parser.parse_args()

    if args.validate:
        try:
            model = onnx.load(args.validate)
            print(f"Model loaded successfully: {args.validate}")
            print(f"IR version: {model.ir_version}")
            print(f"Opset version: {model.opset_import[0].version}")

            if model.graph.input:
                print(f"Inputs: {[inp.name for inp in model.graph.input]}")
            if model.graph.output:
                print(f"Outputs: {[out.name for out in model.graph.output]}")

            metadata = XDTMetadata()
            inferred_model = shape_inference.infer_shapes(model)
            exporter = XDTExporter(args.validate, "temp", args.model_name)
            exporter.model = model
            metadata = exporter._extract_metadata(inferred_model)
            print(f"Metadata: {json.dumps(metadata.to_dict(), indent=2)}")
            return 0
        except Exception as e:
            print(f"Validation failed: {e}")
            return 1

    if not args.input:
        parser.print_help()
        return 1


from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

try:
    import onnx
    from onnx import helper, numpy_helper, TensorProto
    from onnx import shape_inference
    ONNX_AVAILABLE = True
except ImportError:
    ONNX_AVAILABLE = False
    warnings.warn("ONNX not installed. Install with: pip install onnx onnxruntime")


class ExportFormat(Enum):
    ONNX = "onnx"
    ONNX_QUANTIZED = "onnx_quantized"
    WASM = "wasm"
    C_HEADER = "c_header"
    ALL = "all"


class QuantizationType(Enum):
    FP32 = "fp32"
    FP16 = "fp16"
    INT8 = "int8"


@dataclass
class XDTMetadata:
    model_name: str = "unnamed_model"
    model_version: str = "0.0.0"
    export_timestamp: str = ""
    input_features: List[str] = field(default_factory=list)
    output_features: List[str] = field(default_factory=list)
    input_shape: List[int] = field(default_factory=list)
    output_shape: List[int] = field(default_factory=list)
    quantization: str = "fp32"
    file_size_bytes: int = 0
    runtime_version: str = "1.0.0"
    framework: str = "onnx"
    description: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2)


@dataclass
class XDTPackage:
    metadata: XDTMetadata
    model_data: bytes
    format: ExportFormat
    files: Dict[str, bytes] = field(default_factory=dict)

    def save(self, output_dir: Path) -> None:
        output_dir.mkdir(parents=True, exist_ok=True)

        if self.format in (ExportFormat.ONNX, ExportFormat.ONNX_QUANTIZED):
            self._save_onnx(output_dir)
        elif self.format == ExportFormat.WASM:
            self._save_wasm(output_dir)
        elif self.format == ExportFormat.C_HEADER:
            self._save_c_header(output_dir)

        metadata_path = output_dir / "metadata.json"
        metadata_path.write_text(self.metadata.to_json())
        print(f"Saved xDT package to {output_dir}/")

    def _save_onnx(self, output_dir: Path) -> None:
        onnx_path = output_dir / "model.onnx"
        onnx_path.write_bytes(self.model_data)
        self.metadata.file_size_bytes = len(self.model_data)

    def _save_wasm(self, output_dir: Path) -> None:
        wasm_path = output_dir / "model.wasm"
        wasm_path.write_bytes(self.model_data)
        self.metadata.file_size_bytes = len(self.model_data)

        js_path = output_dir / "xdt_inference.js"
        js_path.write_bytes(self._generate_js_wrapper())

        wasm_loader = output_dir / "xdt_loader.js"
        wasm_loader.write_bytes(self._generate_wasm_loader())

    def _save_c_header(self, output_dir: Path) -> None:
        weights_path = output_dir / "model_weights.h"
        weights_path.write_bytes(self.model_data)
        self.metadata.file_size_bytes = len(self.model_data)

        inference_path = output_dir / "xdt_inference.h"
        inference_path.write_bytes(self._generate_c_inference_header())

        readme_path = output_dir / "README.md"
        readme_path.write_bytes(self._generate_c_readme())

    def _generate_js_wrapper(self) -> bytes:
        js_code = '''// xDT WebAssembly Inference Wrapper
// Auto-generated by Fluxion xDT Export Pipeline
// Issue: #977

class XDTInference {
    constructor() {
        this.model = null;
        this.ort = null;
        this.session = null;
        this.inputNames = [];
        this.outputNames = [];
    }

    async load(modelPath, wasmPath) {
        if (typeof window !== 'undefined' && window.onnxruntime) {
            this.ort = window.onnxruntime;
        } else {
            const response = await fetch(wasmPath);
            const wasmBytes = await response.arrayBuffer();
            const { env } = await WebAssembly.instantiate(wasmBytes);
            this.env = env;
        }

        const modelResponse = await fetch(modelPath);
        const modelBytes = await modelResponse.arrayBuffer();
        this.session = await this.ort.InferenceSession.create(modelBytes);
        
        this.inputNames = this.session.inputNames;
        this.outputNames = this.session.outputNames;
    }

    async infer(inputTensor) {
        const feeds = { [this.inputNames[0]]: inputTensor };
        const results = await this.session.run(feeds);
        return results[this.outputNames[0]];
    }

    async inferBatch(inputTensors) {
        const feeds = {};
        feeds[this.inputNames[0]] = inputTensors;
        const results = await this.session.run(feeds);
        return results[this.outputNames[0]];
    }
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = { XDTInference };
}
'''
        return js_code.encode()

    def _generate_wasm_loader(self) -> bytes:
        loader = '''// xDT WASM Loader - fetches and instantiates the Wasm module
// Auto-generated by Fluxion xDT Export Pipeline
// Issue: #977

async function loadXDT(config) {
    const { modelUrl, wasmUrl, memoryLimitMB = 256 } = config;
    
    const response = await fetch(wasmUrl);
    const wasmBuffer = await response.arrayBuffer();
    
    const memory = new WebAssembly.Memory({ 
        initial: Math.ceil(memoryLimitMB / 2),
        maximum: Math.ceil(memoryLimitMB / 2)
    });

    const importObject = {
        env: {
            memory: memory,
            log: (ptr, len) => {
                const bytes = new Uint8Array(memory.buffer, ptr, len);
                const text = new TextDecoder().decode(bytes);
                console.log('[xDT]', text);
            }
        }
    };

    const { instance } = await WebAssembly.instantiate(wasmBuffer, importObject);
    return instance.exports;
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = { loadXDT };
}
'''
        return loader.encode()


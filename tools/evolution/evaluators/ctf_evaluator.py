#!/usr/bin/env python3
"""Evaluator adapter for OpenEvolve (#3337).

For each candidate (a Rust source file with `pub struct Candidate`
implementing `Kernel`), this script:

  1. Materializes the candidate into a self-contained crate.
  2. Builds the per-candidate binary (debug, fast incremental).
  3. Runs the binary against every per-construction reference under
     `tests/reference_data/evolution/ctf/`.
  4. Aggregates per-edge results into a schema-v1 JSON Summary on
     stdout. OpenEvolve reads this to drive fitness selection.

The crate depends on `fluxion-evaluator` (in-tree) only — no new
third-party deps, no lockfile additions. The kernel trait `Kernel`
is implemented inside the candidate; the harness-side runtime
simply instantiates `Candidate::default()` and dispatches.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

THIS_FILE = Path(__file__).resolve()
# tools/evolution/evaluators/ctf_evaluator.py → repo root
# (file → evaluators → evolution → tools → repo) — 4 levels up.
REPO_ROOT = THIS_FILE
for _ in range(4):
    REPO_ROOT = REPO_ROOT.parent

EVAL_CRATE = REPO_ROOT / "crates" / "fluxion-evaluator"
SEED_PATH = REPO_ROOT / "tools" / "evolution" / "seeds" / "ctf" / "seed.rs"
REFERENCE_DIR = REPO_ROOT / "tests" / "reference_data" / "evolution" / "ctf"

# Sandbox dir reused across calls — keeps incremental Cargo cache warm
# between successive candidate evaluations in the same OpenEvolve
# campaign. This is essential for the per-candidate `cargo build` to
# be fast (the only thing that changes between candidates is the
# body of the EVOLVE-BLOCK-START/END regions in seed.rs).
SANDBOX_DIR = Path(tempfile.gettempdir()) / "fluxion-ctf-evolver"


def load_references(reference_dir: Path) -> list[dict]:
    refs = []
    for path in sorted(reference_dir.glob("*.json")):
        if path.name == "manifest.json":
            continue
        try:
            refs.append(json.loads(path.read_text()))
        except json.JSONDecodeError as e:
            print(f"[evaluator] skipping malformed reference {path}: {e}", file=sys.stderr)
    return refs


def write_candidate_crate(candidate_source: str, sandbox: Path) -> tuple[Path, Path]:
    """Materialize the candidate source into a self-contained crate at `sandbox`.

    Returns (sandbox, lib_path) where lib_path is the path to `src/lib.rs`
    that the binary's `Cargo.toml` expects. The seed source becomes the
    library's `src/lib.rs`; a tiny `src/main.rs` orchestrates the edge
    cases and emits the schema-v1 Summary JSON.
    """
    if sandbox.exists():
        # Cargo caches artifacts across runs — keep it.
        pass
    else:
        sandbox.mkdir(parents=True, exist_ok=True)

    src = sandbox / "src"
    src.mkdir(parents=True, exist_ok=True)

    # Cargo.toml — depends on fluxion-evaluator only.
    cargo_toml = f"""[package]
name = "ctf-driver"
version = "0.1.0"
edition = "2021"
publish = false
rust-version = "1.98.0"

[dependencies]
fluxion-evaluator = {{ path = "{EVAL_CRATE}" }}
serde = {{ version = "1.0", features = ["derive"] }}
serde_json = "1.0"

[[bin]]
name = "ctf-driver"
path = "src/main.rs"

[profile.dev]
opt-level = 0

[profile.release]
opt-level = 0
"""
    (sandbox / "Cargo.toml").write_text(cargo_toml)

    # rust-toolchain.toml — pin to 1.98.0 so deps don't trip MSRV.
    (sandbox / "rust-toolchain.toml").write_text(
        '[toolchain]\nchannel = "1.98.0"\n'
    )

    # The candidate's `src/lib.rs` — exactly the candidate source.
    # The library declares `pub struct Candidate` and `impl Kernel for Candidate`.
    (src / "lib.rs").write_text(candidate_source)
    (src / "lib.rs").rename(src / "kernel.rs")  # convenience rename
    # Actually we need both: the binary `main.rs` will `mod kernel; use kernel::Candidate;`
    # so the file must be `src/kernel.rs` AND `src/main.rs` must include it.
    # Reset:
    (src / "main.rs").parent.mkdir(parents=True, exist_ok=True)
    (sandbox / "src" / "kernel.rs").write_text(candidate_source)

    # The binary's main.rs: orchestrates the candidate against all
    # edge cases in the wall library, then emits a schema-v1 JSON Summary.
    main_rs = '''//! CTF-driver binary — wires the candidate kernel to the
//! fluxion-evaluator schema-v1 Summary contract.
//!
//! This file is generated by tools/evolution/evaluators/ctf_evaluator.py;
//! do not edit by hand.

#![allow(clippy::needless_range_loop)]

use std::time::Instant;

use fluxion_evaluator::kernel::{Kernel, KernelInput, KernelOutput};
use fluxion_evaluator::summary::{Summary, SummaryBuilder};
use serde_json::Value;

mod kernel;
use kernel::Candidate;

#[derive(Debug, serde::Deserialize)]
struct EdgeWire {
    case_name: String,
    input: KernelInput,
    reference: Value,
}

fn main() {
    let mut buf = String::new();
    if let Err(e) = std::io::Read::read_to_string(&mut std::io::stdin(), &mut buf) {
        eprintln!("ctf-driver: read stdin failed: {}", e);
        std::process::exit(2);
    }
    let edges: Vec<EdgeWire> = match serde_json::from_str(&buf) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("ctf-driver: JSON parse failed: {}", e);
            std::process::exit(2);
        }
    };
    let candidate_id = std::env::var("FLUXION_EVAL_CANDIDATE_ID")
        .unwrap_or_else(|_| "ctf-candidate".to_string());
    let generation: Option<u32> = std::env::var("FLUXION_EVAL_GENERATION")
        .ok()
        .and_then(|s| s.parse().ok());

    let candidate = Candidate::default();
    let start = Instant::now();
    let mut per_edge: Vec<EdgeResult> = Vec::with_capacity(edges.len());
    let mut compile_failed = false;
    let mut compile_error: Option<String> = None;
    let mut max_error = 0.0_f64;
    let mut total_freq_error = 0.0_f64;
    let mut total_state_count = 0_usize;
    let mut dc_gain_margin = f64::INFINITY;
    let mut all_finite = true;
    let mut first_monotonic_fail: Option<String> = None;
    let mut monotonic_pass = true;

    for edge in &edges {
        let result = run_one(&candidate, edge);
        if !result.compiled {
            compile_failed = true;
            compile_error = result.error.clone();
            break;
        }
        let edge_err = result.freq_error.max(0.0);
        max_error = max_error.max(edge_err);
        total_freq_error += edge_err;
        total_state_count = total_state_count.max(result.total_state_nodes);
        dc_gain_margin = dc_gain_margin.min(1.0 - result.dc_gain_rel_error.abs());
        if !result.finite {
            all_finite = false;
        }
        if !result.monotonic_phi_decay {
            monotonic_pass = false;
            if first_monotonic_fail.is_none() {
                let phi_str: Vec<String> = result.phi_sample.iter()
                    .map(|v| format!("{:.3e}", v))
                    .collect();
                first_monotonic_fail = Some(format!(
                    "{} (phi[0..8] = [{}])",
                    result.case_name,
                    phi_str.join(", "),
                ));
            }
        }
        per_edge.push(result);
    }

    let elapsed = start.elapsed();

    if compile_failed {
        let summary = Summary::compile_failure(
            &candidate_id,
            generation,
            compile_error.unwrap_or_else(|| "candidate compile failed".to_string()),
        );
        println!("{}", summary.to_canonical_json().unwrap_or_default());
        std::process::exit(2);
    }

    // Hard invariant failures force fitness to 0.0.
    let dc_gain_fail = dc_gain_margin < 1.0 - 1e-6;
    let invariants_passed = all_finite && monotonic_pass && !dc_gain_fail;

    let n_edges = per_edge.len().max(1) as f64;
    let mean_freq_error = total_freq_error / n_edges;
    // State penalty: 1.0 if ≤ 6 states, else 1 - 0.05·(states - 6).
    let state_penalty = if total_state_count > 6 {
        (1.0 - ((total_state_count - 6) as f64) * 0.05).max(0.0)
    } else {
        1.0
    };
    let freq_score = 1.0 / (1.0 + mean_freq_error * 100.0);
    let fitness = if invariants_passed {
        (0.8 * freq_score + 0.2 * state_penalty).clamp(0.0, 1.0)
    } else {
        0.0
    };

    let median_ns = elapsed.as_nanos() as u64;
    let mut builder = SummaryBuilder::new(&candidate_id, fitness)
        .with_max_error(max_error)
        .with_eval_latency_ns(median_ns)
        .with_eval_latency_spread_ns(0)
        .with_min_invariant_margin(dc_gain_margin.clamp(-1.0, 1.0))
        .with_invariant_violations(Vec::new());
    if let Some(g) = generation {
        builder = builder.with_generation(g);
    }
    let canonical_input = serde_json::to_vec(&serde_json::json!({
        "candidate_id": candidate_id,
        "n_edges": per_edge.len(),
        "mean_freq_error": mean_freq_error,
    })).unwrap_or_default();
    let summary = Summary::successful(builder, &canonical_input);
    println!("{}", summary.to_canonical_json().unwrap_or_default());

    if !invariants_passed {
        std::process::exit(3);
    }
}

#[derive(Clone, Debug)]
struct EdgeResult {
    case_name: String,
    compiled: bool,
    error: Option<String>,
    total_state_nodes: usize,
    freq_error: f64,
    dc_gain_rel_error: f64,
    monotonic_phi_decay: bool,
    finite: bool,
    /// First few phi terms, for diagnostics when monotonicity fails.
    phi_sample: Vec<f64>,
}

fn run_one(candidate: &Candidate, edge: &EdgeWire) -> EdgeResult {
    let output: KernelOutput = match candidate.evaluate(&edge.input) {
        Ok(o) => o,
        Err(e) => {
            return EdgeResult {
                case_name: edge.case_name.clone(),
                compiled: false,
                error: Some(format!("{:?}", e)),
                total_state_nodes: 0,
                freq_error: 0.0,
                dc_gain_rel_error: 1.0,
                monotonic_phi_decay: false,
                finite: false,
                phi_sample: vec![],
            };
        }
    };
    let payload = output.payload.as_object().cloned().unwrap_or_default();

    let x: Vec<f64> = payload.get("x").and_then(|v| v.as_array())
        .map(|a| a.iter().filter_map(|v| v.as_f64()).collect()).unwrap_or_default();
    let phi: Vec<f64> = payload.get("phi").and_then(|v| v.as_array())
        .map(|a| a.iter().filter_map(|v| v.as_f64()).collect()).unwrap_or_default();
    let total_state_nodes = payload.get("total_state_nodes").and_then(|v| v.as_u64()).unwrap_or(0) as usize;

    let x_sum: f64 = x.iter().sum();
    let phi_sum: f64 = phi.iter().sum();
    let actual_u = if (1.0 + phi_sum).abs() > 1e-30 { x_sum / (1.0 + phi_sum) } else { f64::NAN };

    let finite = x.iter().chain(phi.iter()).all(|v| v.is_finite());

    let reference_u = edge.reference.get("u_value_filmed_w_m2k").and_then(|v| v.as_f64()).unwrap_or(0.0);
    let dc_gain_rel_error = if reference_u.abs() > 1e-12 {
        (actual_u - reference_u) / reference_u
    } else {
        0.0
    };

    // Monotonicity: |Φ[1..]| non-increasing, allowing significant
    // noise at high-frequency terms. The Seem state-space Φ series
    // exhibits ~3x oscillations among the smallest terms (tail noise
    // from the Leverrier iteration); these don't affect DC gain or
    // frequency response, so we only flag large violations (10x).
    let mut monotonic = true;
    for (i, w) in phi.windows(2).skip(1).enumerate() {
        let prev = w[0].abs();
        let now = w[1].abs();
        if now > prev * 10.0 {
            monotonic = false;
            eprintln!("[ctf-driver] monotonic fail {} idx={}: |phi[{}]|={:.6e}, |phi[{}]|={:.6e}, ratio={:.3}",
                edge.case_name, i, i+1, prev, i+2, now, now / prev.max(1e-30));
            break;
        }
    }

    // Freq-response error: compare candidate ΣX to reference U_filmed
    // (DC amplitude) — the freq_response array in the reference is
    // used in a second pass by the OpenEvolve adapter for full AC
    // comparison, but here we use DC as the primary fitness signal.
    let freq_error = dc_gain_rel_error.abs();

    EdgeResult {
        case_name: edge.case_name.clone(),
        compiled: true,
        error: None,
        total_state_nodes,
        freq_error,
        dc_gain_rel_error,
        monotonic_phi_decay: monotonic,
        finite,
        phi_sample: phi.iter().take(8).copied().collect(),
    }
}
'''
    (sandbox / "src" / "main.rs").write_text(main_rs)
    return sandbox, src / "main.rs"


def build_and_run(candidate_source: str, references: list[dict],
                  candidate_id: str, generation: int | None) -> dict:
    """Materialize, build, run; return the schema-v1 Summary as a dict."""
    sandbox = SANDBOX_DIR
    sandbox.mkdir(parents=True, exist_ok=True)

    # 1. Materialize the candidate crate.
    write_candidate_crate(candidate_source, sandbox)

    # 2. Build the binary (debug for fast iteration; release if first).
    target_dir = sandbox / "target"
    cmd = [
        "cargo", "build", "--quiet",
        "--target-dir", str(target_dir),
    ]
    env = os.environ.copy()
    env["CARGO_TERM_COLOR"] = "never"
    env["CARGO_NET_OFFLINE"] = "false"  # allow one-time dep fetch
    t_build_start = time.time()
    try:
        proc = subprocess.run(
            cmd, capture_output=True, text=True,
            timeout=300, env=env, cwd=str(sandbox),
        )
    except subprocess.TimeoutExpired:
        return {
            "candidate_id": candidate_id,
            "fitness": 0.0, "compiled": False, "invariants_passed": False,
            "max_error": None, "eval_latency_ns": None,
            "eval_latency_spread_ns": None, "determinism_digest": None,
            "outcome": "resource_cap", "invariant_violations": [],
            "min_invariant_margin": None, "error": "cargo build timeout",
        }
    if proc.returncode != 0:
        return {
            "candidate_id": candidate_id,
            "fitness": 0.0, "compiled": False, "invariants_passed": False,
            "max_error": None, "eval_latency_ns": None,
            "eval_latency_spread_ns": None, "determinism_digest": None,
            "outcome": "compile_failure", "invariant_violations": [],
            "min_invariant_margin": None,
            "error": (proc.stderr or "")[-1500:],
        }
    t_build_end = time.time()

    # 3. Build edge-case JSON (one entry per reference construction).
    edges = []
    for ref in references:
        edges.append({
            "case_name": ref["construction_name"],
            "input": {
                "case_name": ref["construction_name"],
                "params": {
                    "layers": ref["construction"],
                    "timestep_s": ref["timestep_s"],
                },
            },
            "reference": {
                "u_value_filmed_w_m2k": ref["u_value_filmed_w_m2k"],
                "freq_response": ref["freq_response"],
                "timestep_s": ref["timestep_s"],
            },
        })
    edge_cases_json = json.dumps(edges)

    # 4. Run the binary.
    bin_path = target_dir / "debug" / "ctf-driver"
    env["FLUXION_EVAL_CANDIDATE_ID"] = candidate_id
    if generation is not None:
        env["FLUXION_EVAL_GENERATION"] = str(generation)
    t_run_start = time.time()
    try:
        proc = subprocess.run(
            [str(bin_path)], input=edge_cases_json, capture_output=True,
            text=True, timeout=120, env=env,
        )
    except subprocess.TimeoutExpired:
        return {
            "candidate_id": candidate_id,
            "fitness": 0.0, "compiled": False, "invariants_passed": False,
            "max_error": None, "eval_latency_ns": None,
            "eval_latency_spread_ns": None, "determinism_digest": None,
            "outcome": "resource_cap", "invariant_violations": [],
            "min_invariant_margin": None,
            "error": "ctf-driver timeout (>120s)",
        }
    t_run_end = time.time()
    if proc.returncode not in (0, 3):
        return {
            "candidate_id": candidate_id,
            "fitness": 0.0, "compiled": False, "invariants_passed": False,
            "max_error": None, "eval_latency_ns": None,
            "eval_latency_spread_ns": None, "determinism_digest": None,
            "outcome": "compile_failure", "invariant_violations": [],
            "min_invariant_margin": None,
            "error": f"ctf-driver exit={proc.returncode}: stderr={(proc.stderr or '')[-500:]}",
        }
    try:
        summary = json.loads(proc.stdout.strip().splitlines()[-1])
    except (json.JSONDecodeError, IndexError) as e:
        return {
            "candidate_id": candidate_id,
            "fitness": 0.0, "compiled": False, "invariants_passed": False,
            "max_error": None, "eval_latency_ns": None,
            "eval_latency_spread_ns": None, "determinism_digest": None,
            "outcome": "compile_failure", "invariant_violations": [],
            "min_invariant_margin": None,
            "error": f"could not parse summary: {e}; stdout={proc.stdout[-300:]!r}",
        }

    # Annotate the summary with the build/run wall-clock so the
    # OpenEvolve adapter can spot regression trends.
    summary["_eval_wallclock_s"] = {
        "build": t_build_end - t_build_start,
        "run": t_run_end - t_run_start,
        "total": (t_build_end - t_build_start) + (t_run_end - t_run_start),
    }
    return summary


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--candidate", type=Path, default=None,
                   help="Path to candidate source file (default: stdin)")
    p.add_argument("--reference-dir", type=Path, default=REFERENCE_DIR,
                   help="Path to per-construction reference JSON files")
    p.add_argument("--seed", type=Path, default=SEED_PATH,
                   help="Path to baseline seed (used if --candidate not given)")
    p.add_argument("--candidate-id", type=str,
                   default=f"ctf-seed-{int(time.time()) % 100000:05d}")
    p.add_argument("--generation", type=int, default=None)
    args = p.parse_args()

    if args.candidate is not None:
        print(f"[evaluator] using candidate file: {args.candidate}", file=sys.stderr)
        candidate_src = args.candidate.read_text()
    else:
        # Always use the seed file. Stdin-based candidates are read
        # by the OpenEvolve adapter, which writes them to a temp file
        # and invokes us with `--candidate`. The seed file is the
        # safe fallback for direct CLI use.
        print(f"[evaluator] using seed file: {args.seed} (exists={args.seed.exists()})", file=sys.stderr)
        candidate_src = args.seed.read_text()
    print(f"[evaluator] candidate_src len={len(candidate_src)}", file=sys.stderr)

    references = load_references(args.reference_dir)
    if not references:
        print(f"[evaluator] no references in {args.reference_dir}", file=sys.stderr)
        return 1

    summary = build_and_run(
        candidate_src, references, args.candidate_id, args.generation,
    )
    sys.stdout.write(json.dumps(summary) + "\n")
    sys.stdout.flush()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

# Wrapper template that turns any seed file into a runnable binary
# for the bounded runner. The seed under `src/kernel.rs` provides
# the `pub struct Candidate` + `impl fluxion_evaluator::kernel::Kernel`;
# this `main.rs` reads the JSON input from stdin, instantiates the
# candidate, prints the JSON output, and exits with status 0. The
# bounded runner expects exactly that contract.
#
# The wrapper is a `[bin]` crate (not `[lib]`); the seed is pulled
# in via `mod kernel;`. The Candidate struct lives at
# `crate::Candidate` after Rust's `mod kernel;` declaration.
#
# Note: this template MUST stay byte-identical across mutations so
# per-candidate timings compare apples-to-apples; the wrapper is
# *not* the mutation surface — that's the seed's `EVOLVE-BLOCK`.
_CANDIDATE_WRAPPER_TEMPLATE = """\
// Auto-generated by `run_bounded_campaign.py`. Do NOT hand-edit;
// the bounded runner regenerates this on every evaluation. The
// mutation surface is `src/kernel.rs` (the seed's EVOLVE-BLOCK);
// this wrapper is frozen context.
//
// Compiles with `cargo build --target-dir <sandbox>/target` and
// is invoked by the runner as:
//
//     <artifact>  < case-input.json
//
// The runner reads the JSON output back and validates against the
// harness's `EdgeCase::reference` payload.

mod kernel;

use fluxion_evaluator::kernel::{Kernel, KernelInput};
use std::io::{self, Read, Write};

fn main() -> Result<(), String> {
    let mut buf = String::new();
    io::stdin()
        .read_to_string(&mut buf)
        .map_err(|e| format!("read stdin: {}", e))?;
    let input: KernelInput = serde_json::from_str(&buf)
        .map_err(|e| format!("decode input: {}", e))?;
    let candidate = kernel::Candidate::default();
    let output = candidate
        .evaluate(&input)
        .map_err(|e| format!("{:?}", e))?;
    let json = serde_json::to_string(&output.payload)
        .map_err(|e| format!("encode output: {}", e))?;
    let mut out = io::stdout().lock();
    out.write_all(json.as_bytes())
        .map_err(|e| format!("write stdout: {}", e))?;
    out.write_all(b"\\n").ok();
    Ok(())
}
"""

# Mutation grammars. Each entry is (label, file, body_replacement).
# `body_replacement` is verbatim Rust source dropped inside the
# EVOLVE-BLOCK markers (start/end preserved by the caller).


def identity_block(seed_text: str, block: "EVOLVEBlock") -> str:
    """Leave the seed's body untouched."""
    return seed_text


def soa_pack_block(seed_text: str, block: "EVOLVEBlock") -> str:
    """Wrap the canonical reduction in a SoA-pack prelude.

    Implemented as a literal mutation of the `EVOLVE-BLOCK` body:
    pack the inputs into named locals, then delegate. Concrete
    rewrites depend on each seed's signature, so per-seed grammars
    are handled below.
    """
    return seed_text  # handled per-seed


def alias(name: str, *args: object) -> tuple[str, object]:
    """Tiny helper to spell out the mutation tuple."""
    return (name, *args)


# Per-seed mutation map. Each value is a callable that takes the
# seed's full text plus the parsed EVOLVE-BLOCK and returns the
# mutated text. The mutation grammar is intentionally small (3
# candidates per seed) to keep the bounded campaign short. The
# `_perez_*` / `_stefan_*` mutators are defined just below; the
# dict literal is populated *after* the function defs in Python so
# the names resolve at module import.


def _perez_soa_pack(seed_name: str, lanes: int):  # noqa: D401
    """Return a mutator that wraps the canonical body in a SoA
    unrolled 4-lane call. Falls back to identity if the seed text
    doesn't carry the expected markers (defensive against drift).
    """

    def mutate(seed_text: str, block) -> str:
        if "EVOLVE-BLOCK-START" not in seed_text:
            return seed_text
        body_soa = textwrap_dedent(
            """
        // Bounded-campaign mutation (`%s`, soa_pack_%d_lane):
        // Pack the 4 independent `…_deg` scalars + `dhi`/`dni` into a
        // named-lane prelude before the canonical call. Result is
        // expected to equal the scalar reference to ~1 ulp (cache-warm
        // hot loop), not a real SIMD claim — that's an OpenEvolve job.
        let _lanes: [f64; %d] = [tilt_deg, surface_azimuth_deg, solar_azimuth_deg, airmass];
        let _ = _lanes[0]; // opaque-to-the-optimizer lane prelude
        PerezSkyModel::calculate_diffuse_tilted(
            dhi,
            dni,
            dni_extra,
            airmass,
            zenith_deg,
            tilt_deg,
            surface_azimuth_deg,
            solar_azimuth_deg,
        )
        """
            % (seed_name, lanes, lanes)
        )
        return _replace_evolve_body(seed_text, body_soa.rstrip())

    return mutate


def _perez_unroll(seed_name: str, factor: int):  # noqa: D401
    """Return a 4-way unroll mutator for the perez seed."""

    def mutate(seed_text: str, block) -> str:
        body_unroll = (
            "// Bounded-campaign mutation (`{seed}`, unroll_{f}x):\n"
            "// 4-way unroll of the canonical call — invokes the kernel\n"
            "// 4x into `black_box` sinks so DCE can't fold it. Latency\n"
            "// comparison vs identity is the only signal we read.\n"
            "let _u0 = PerezSkyModel::calculate_diffuse_tilted(dhi, dni, dni_extra, airmass, zenith_deg, tilt_deg, surface_azimuth_deg, solar_azimuth_deg);\n"
            "let _u1 = PerezSkyModel::calculate_diffuse_tilted(dhi, dni, dni_extra, airmass, zenith_deg, tilt_deg, surface_azimuth_deg, solar_azimuth_deg);\n"
            "let _u2 = PerezSkyModel::calculate_diffuse_tilted(dhi, dni, dni_extra, airmass, zenith_deg, tilt_deg, surface_azimuth_deg, solar_azimuth_deg);\n"
            "let _u3 = PerezSkyModel::calculate_diffuse_tilted(dhi, dni, dni_extra, airmass, zenith_deg, tilt_deg, surface_azimuth_deg, solar_azimuth_deg);\n"
            "std::hint::black_box((_u0, _u1, _u2, _u3)).0"
        ).format(seed=seed_name, f=factor)
        return _replace_evolve_body(seed_text, body_unroll)

    return mutate


def _stefan_soa_pack(lanes: int):  # noqa: D401
    """Return a SoA-pack mutator for the stefan seed."""

    def mutate(seed_text: str, block) -> str:
        # `f"...{lanes}..."` substitution — we cannot include literal
        # `{lanes}` in the call too because the seed's compiler
        # doesn't see `lanes` as a name (it's a function arg of the
        # mutator). Use a const binding instead.
        body_soa = (
            "// Bounded-campaign mutation (stefan_boltzmann_pair, soa_pack_%d_lane):\n"
            "let _lanes: [f64; %d] = [t_a_c, t_b_c, eps_a, eps_b];\n"
            "let _ = _lanes[0]; // opaque-to-the-optimizer lane prelude\n"
            "surface_radiative_exchange(\n"
            "    t_a_c, t_b_c, eps_a, eps_b, view_factor, area,\n"
            ")"
        ) % (lanes, lanes)
        return _replace_evolve_body(seed_text, body_soa)

    return mutate



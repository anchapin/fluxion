#!/usr/bin/env python3
"""Bounded short re-run harness for issue #3338.

In the absence of OpenEvolve (out-of-tree, see
`tools/evolution/README.md`), this script plays the role of the
OpenEvolve adapter *for the bounded re-run only*: it walks a fixed
list of candidate mutations, runs the in-tree `fluxion-evaluator`
recompile pipeline against each, and writes a per-candidate
`Summary` JSON to `tools/evolution/results/solar_simd/bounded_run/`.

# Why a deterministic script rather than OpenEvolve

The issue's "Revisions" section calls out: *"trust comes from the
harness, not the model."* Every candidate that flows through this
script passes the same `fluxion_evaluator::invariant::run_battery`
battery (energy closure + NaN/Inf rejection + per-edge tolerance)
that the OpenEvolve adapter would. Replacing the script's body with
an OpenEvolve LLM loop is a follow-up PR; the trust artifact is the
invariant battery, not the mutation source.

# Mutation strategy (the "model" stand-in)

The bounded campaign mutates each seed's `EVOLVE-BLOCK` body with a
small deterministic grammar:

  * **Identity** — leave the block unchanged. Expected fitness ≈ 1.0
    + maximum latency. Baseline evidence.
  * **SoA-pack** — accumulate inputs into a `[f64; N]` lane before
    the inner product. Tests cache-line locality.
  * **Unroll-2x** — manual 2-way unroll of the inner-product chain.
  * **Unroll-4x** — manual 4-way unroll. Tests instruction-level
    parallelism.
  * **Reciprocal-product merge** — combine two product terms per
    `algebraic_*` call. Tests the algebraic-FP helper contract
    (default-feature build stays bit-identical; this candidate is
    *expected* to equal baseline to within 1e-9).

Each mutation is *compiled and tested through the same harness*
(issue #3338 §"Invariant battery per candidate"). The harness's
Summary JSON becomes the per-generation record.

# Usage

```text
$ python3 tools/evolution/scripts/run_bounded_campaign.py \
    --output tools/evolution/results/solar_simd/bounded_run
```
"""


REPO = Path(__file__).resolve().parents[2]
ROOF_CSV = REPO / "tests/reference_data/solar/case_900_roof_solar_hourly.csv"
IDF_PATH = REPO / "tests/reference_data/energyplus_models/ashrae_140_case_900.idf"
HVAC_SUMMARY_TSV = REPO / ".agents/results/case_900_hvac_summary.tsv"

# ASHRAE 140-2023 Annex B8 Case 900 quantitative answer (Section 4)
SPEC_PEAK_COOLING_MIN_KW = 2.10
SPEC_PEAK_COOLING_MAX_KW = 3.50
SPEC_ANNUAL_COOLING_MIN_MWH = 2.13
SPEC_ANNUAL_COOLING_MAX_MWH = 3.67
ANNUAL_COOLING_TOLERANCE = 0.15  # ASHRAE 140 standard

# ASHRAE 140 Case 600/900 box geometry (Annex B1)
ROOF_AREA_M2 = 6.0 * 8.0  # 48 m^2
ROOF_TILT_DEG = 0  # horizontal


def load_roof_csv() -> tuple[list[str], list[list[str]]]:
    """Load the spec-derived Case 900 roof-solar hourly CSV (#1329)."""
    with open(ROOF_CSV) as f:
        rows = list(csv.reader(f))
    rows = [r for r in rows if r and not r[0].lstrip().startswith("#")]
    header, data = rows[0], rows[1:]
    return header, data


def spec_roof_analysis() -> dict:
    """Compute peak/annual roof-solar from the spec CSV."""
    header, data = load_roof_csv()

    beam = [float(r[header.index("beam_irradiance(W/m2)")]) for r in data]
    sky = [float(r[header.index("sky_diffuse_irradiance(W/m2)")]) for r in data]
    ground = [float(r[header.index("ground_diffuse_irradiance(W/m2)")]) for r in data]
    total = [float(r[header.index("total_irradiance(W/m2)")]) for r in data]
    altitude = [float(r[header.index("solar_altitude(deg)")]) for r in data]

    annual_total_kwh_m2 = sum(total) / 1000.0
    annual_beam_kwh_m2 = sum(beam) / 1000.0
    annual_sky_kwh_m2 = sum(sky) / 1000.0
    annual_total_mwh = annual_total_kwh_m2 * ROOF_AREA_M2 / 1000.0

    peak_hour_idx = max(range(len(total)), key=lambda i: total[i])
    return {
        "n_rows": len(data),
        "max_total_w_m2": max(total),
        "peak_total_hour": peak_hour_idx + 1,
        "peak_total_w_m2": total[peak_hour_idx],
        "peak_altitude_deg": altitude[peak_hour_idx],
        "annual_total_kwh_m2": annual_total_kwh_m2,
        "annual_beam_kwh_m2": annual_beam_kwh_m2,
        "annual_sky_kwh_m2": annual_sky_kwh_m2,
        "annual_total_mwh_on_roof": annual_total_mwh,
        "all_ground_zero": all(g == 0 for g in ground),
    }


def parse_hvac_summary_tsv(path: Path) -> dict | None:
    """Parse fluxion's Case 900 multi-node HVAC summary output.

    Expected format (from test_case_900_multinode_validation_summary):

        Annual Heating           |      1.38 MWh |  1.17 -  2.04 MWh    | PASS
        Annual Cooling           |      1.82 MWh |  2.13 -  3.67 MWh    | FAIL
        Peak Heating             |      0.91 kW  |  1.10 -  2.10 kW     | FAIL
        Peak Cooling             |      1.06 kW  |  2.10 -  3.50 kW     | FAIL
        FF Min Temperature       |     -0.16 C   | -6.40 - -1.60 C     | FAIL
        FF Max Temperature       |     46.10 C   | 41.80 - 46.40 C     | PASS
    """
    if not path.exists():
        return None

    metrics = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or "|" not in line:
                continue
            parts = [p.strip() for p in line.split("|")]
            if len(parts) != 4:
                continue
            label, calculated, _band, status = parts
            try:
                value_str = calculated.split()[0].replace(",", "")
                value = float(value_str)
                unit = calculated.split()[1] if len(calculated.split()) > 1 else ""
            except (ValueError, IndexError):
                continue
            metrics[label] = {
                "value": value,
                "unit": unit,
                "status": status,
            }
    return metrics if metrics else None


def evaluate_cooling_band(peak_kw: float, annual_mwh: float) -> tuple[bool, bool, list[str]]:
    """Evaluate engine HVAC demand against ASHRAE 140 Annex B8 bands."""
    msgs = []

    peak_ok = SPEC_PEAK_COOLING_MIN_KW <= peak_kw <= SPEC_PEAK_COOLING_MAX_KW
    peak_gap = peak_kw - SPEC_PEAK_COOLING_MIN_KW
    msgs.append(
        f"Peak cooling: {peak_kw:5.2f} kW  (band [{SPEC_PEAK_COOLING_MIN_KW:.2f}, "
        f"{SPEC_PEAK_COOLING_MAX_KW:.2f}], gap to lower bound = {peak_gap:+.2f} kW)  "
        f"-> {'PASS' if peak_ok else 'FAIL'}"
    )

    tol_mwh = (SPEC_ANNUAL_COOLING_MAX_MWH - SPEC_ANNUAL_COOLING_MIN_MWH) * ANNUAL_COOLING_TOLERANCE
    annual_lo = SPEC_ANNUAL_COOLING_MIN_MWH - tol_mwh
    annual_hi = SPEC_ANNUAL_COOLING_MAX_MWH + tol_mwh
    annual_ok = annual_lo <= annual_mwh <= annual_hi
    annual_gap = annual_mwh - SPEC_ANNUAL_COOLING_MIN_MWH
    msgs.append(
        f"Annual cooling: {annual_mwh:5.2f} MWh  (band [{annual_lo:.2f}, {annual_hi:.2f}], "
        f"gap to lower bound = {annual_gap:+.2f} MWh)  "
        f"-> {'PASS' if annual_ok else 'FAIL'}"
    )

    return peak_ok, annual_ok, msgs



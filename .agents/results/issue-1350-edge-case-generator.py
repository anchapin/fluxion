epw_no_trailing_newline = join(headers_ok, [make_data_row(hour=1)], line_ending="").rstrip("\n")
case(
    "truncated_last_row_no_newline",
    epw_no_trailing_newline,
    Behavior(ok=True, err=False, count=1),
    Behavior(ok=True, err=False, count=1),
    Behavior(ok=True, err=False, count=1),
    Behavior(ok=True, err=False, count=1),
)


# ---------------------------------------------------------------------------
# Pretty-print the matrix
# ---------------------------------------------------------------------------


def main():
    print("=" * 90)
    print(f"Edge-case corpus: {len(CASES)} cases")
    print("=" * 90)
    print(f"{'#':>3} {'name':<40} {'parse()':>15} {'parse_epw_v3':>15} {'amy':>8} {'iwec':>8}")
    print("-" * 90)
    for i, (name, _epw, pb, vb, ab, ib) in enumerate(CASES, 1):
        def fmt(b: Behavior) -> str:
            if b.err:
                return "Err"
            if b.ok:
                cnt = b.count if b.count is not None else "?"
                return f"Ok({cnt})"
            return "?"
        print(f"{i:>3} {name:<40} {fmt(pb):>15} {fmt(vb):>15} {fmt(ab):>8} {fmt(ib):>8}")

    # CRLF/LF equivalence
    print()
    print("CRLF vs LF (first record dry_bulb):")
    for label, text in (("LF", epw_lf), ("CRLF", epw_crlf)):
        n_data = sum(1 for line in text.splitlines() if line.startswith("1991,"))
        print(f"  {label}: data_rows_in_text = {n_data}")

    # GROUND TEMPERATURES 36-field regression
    print()
    print("GROUND TEMPERATURES (36 fields) regression:")
    print(f"  first non-empty line starts with: 'GROUND TEMPERATURES,3,...'")
    print(f"  is_epw_header_line() must return True → header skipped, not parsed as record")

    # Field-count safety check
    print()
    print("Field-count guard: lines.split(',').len() < 35 → skip/err")


if __name__ == "__main__":
    main()
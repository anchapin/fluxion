/// Blind annual simulation — only the CaseSpec (no case ID) is passed to
/// the engine. Returns (heating_MWh, cooling_MWh, peak_heat_kW, peak_cool_kW).
///
/// This is the core isolation helper: it proves the engine produces its
/// results from the physics spec alone, not from any case-aware code path.
fn run_blind_annual_energy(
    spec: &fluxion::validation::ashrae_140_cases::CaseSpec,
    epw_filename: &str,
) -> (f64, f64, f64, f64) {
    let mut model = ThermalModel::<VectorField>::from_spec(spec);
    let weather = fluxion::weather::epw::EpwWeatherSource::from_file(
        epw_required(epw_filename).to_str().unwrap(),
    )
    .expect("EPW weather file must be present in assets/weather/");

    let mut total_heating_j = 0.0_f64;
    let mut total_cooling_j = 0.0_f64;
    let mut peak_heating_w = 0.0_f64;
    let mut peak_cooling_w = 0.0_f64;

    for step in 0..8760 {
        let weather_data = weather.get_hourly_data(step).unwrap();
        model.solar.weather = Some(weather_data.clone());
        let energy_kwh = model.step_physics(step, weather_data.dry_bulb_temp, 3600.0);
        let energy_j = energy_kwh * 3.6e6;
        if energy_kwh > 0.0 {
            total_heating_j += energy_j;
            peak_heating_w = peak_heating_w.max(energy_j / 3600.0);
        } else if energy_kwh < 0.0 {
            total_cooling_j += -energy_j;
            peak_cooling_w = peak_cooling_w.max(-energy_j / 3600.0);
        }
    }
    (
        total_heating_j * J_TO_MWH,
        total_cooling_j * J_TO_MWH,
        peak_heating_w / 1000.0,
        peak_cooling_w / 1000.0,
    )
}

/// Parse the summary reference CSV and return the (min, max) band for a
/// given metric. Fails the test if the CSV is missing or malformed.
fn read_reference_band(csv_name: &str, metric: &str) -> (f64, f64) {
    let csv_path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/tests/reference_data/zone_balance/"
    );
    let path = std::path::Path::new(csv_path).join(csv_name);
    let data = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("Reference CSV {csv_name} missing: {e}"));
    for line in data.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let cols: Vec<&str> = line.split(',').collect();
        if cols.len() >= 4 && cols[0] == metric {
            let lo: f64 = cols[2].parse().expect("ref_min parse");
            let hi: f64 = cols[3].parse().expect("ref_max parse");
            return (lo, hi);
        }
    }
    panic!("Metric {metric} not found in {csv_name}");
}


/// Helper: simulate a free-floating case and return (min_T, max_T, n_steps).
fn simulate_free_float(case: ASHRAE140Case) -> (f64, f64, usize) {
    let spec = case.spec();
    let mut model = ThermalModel::<VectorField>::from_spec(&spec);
    let weather = DenverTmyWeather::new();

    assert!(spec.is_free_floating(), "Case must be free-floating");

    // Disable HVAC for free-floating mode (Issue #275)
    model.setpoints.heating_setpoint = -999.0;
    model.setpoints.cooling_setpoint = 999.0;
    model.hvac.hvac_heating_capacity = 0.0;
    model.hvac.hvac_cooling_capacity = 0.0;

    let mut min_t = f64::INFINITY;
    let mut max_t = f64::NEG_INFINITY;
    let n_steps = 8760;

    for step in 0..n_steps {
        let weather_data = weather.get_hourly_data(step).unwrap();
        model.solar.weather = Some(weather_data.clone());
        model.step_physics(step, weather_data.dry_bulb_temp, 3600.0);

        if let Some(&t) = model.setpoints.temperatures.as_slice().first() {
            min_t = min_t.min(t);
            max_t = max_t.max(t);
        }
    }
    (min_t, max_t, n_steps)
}

/// ASHRAE 140 Case 600FF — Low-mass free-floating.
///
/// Reference range (ASHRAE 140-2023):
/// - min_T ∈ [-18.8, -15.6]°C
/// - max_T ∈ [64.9, 75.1]°C
///
/// Note: Reference ranges assume a specific TMY file. We use Denver
/// TMY (USA_CO_Denver-Stapleton.Intl.AP.724690_TMY.epw), so we apply a
/// physically-motivated sanity check (finite, in reasonable range) and
/// print actual values for human inspection.
#[test]
fn test_free_floating_case_600ff_isolation() {
    let (min_t, max_t, n) = simulate_free_float(ASHRAE140Case::Case600FF);

    println!(
        "[#1013 Case 600FF] N={n}, T_min={min_t:.2}°C, T_max={max_t:.2}°C, swing={:.2}°C",
        max_t - min_t
    );

    // Acceptance: temperatures are finite, in physically reasonable range,
    // and high-mass swing is smaller than low-mass swing.
    assert!(min_t.is_finite() && max_t.is_finite());
    assert!(min_t < max_t, "min should be < max");
    assert!(
        min_t > -50.0 && min_t < 50.0,
        "T_min {min_t}°C outside physical range"
    );
    assert!(
        max_t > 0.0 && max_t < 100.0,
        "T_max {max_t}°C outside physical range"
    );
    assert_eq!(n, 8760, "Should simulate a full year");
}

/// ASHRAE 140 Case 900FF — High-mass free-floating.
///
/// Reference range (ASHRAE 140-2023):
/// - min_T ∈ [-6.4, -1.6]°C
/// - max_T ∈ [41.8, 46.4]°C
///
/// NOTE: Per Issue #908 / PR #935, the current `FiveR1CSolver` is
/// steady-state only and over-damps the 900FF mass node, so the resulting
/// temperature swing is narrower than the ASHRAE 140 reference.
/// We verify finite behavior + a *physical sanity* bound (high mass →
/// smaller swing than Case 600FF) without failing on absolute reference.
#[test]
fn test_free_floating_case_900ff_isolation() {
    let (min_900, max_900, _) = simulate_free_float(ASHRAE140Case::Case900FF);
    let (min_600, max_600, _) = simulate_free_float(ASHRAE140Case::Case600FF);

    let swing_900 = max_900 - min_900;
    let swing_600 = max_600 - min_600;
    let swing_reduction_pct = (swing_600 - swing_900) / swing_600 * 100.0;

    println!(
        "[#1013 Case 900FF] T_min={min_900:.2}°C, T_max={max_900:.2}°C, swing={swing_900:.2}°C\n\
         [#1013 Case 600FF] T_min={min_600:.2}°C, T_max={max_600:.2}°C, swing={swing_600:.2}°C\n\
         [#1013 swing reduction] 900FF vs 600FF: {swing_reduction_pct:.1}%"
    );

    // Sanity checks — must be finite and physically reasonable.
    assert!(min_900.is_finite() && max_900.is_finite());
    assert!(min_900 < max_900);
    assert!(
        min_900 > -50.0 && min_900 < 50.0,
        "Case 900FF T_min {min_900}°C outside physical range"
    );
    assert!(
        max_900 > 0.0 && max_900 < 100.0,
        "Case 900FF T_max {max_900}°C outside physical range"
    );

    // High mass must damp more than low mass. Allow a generous lower
    // bound (10%) because the steady-state-only 5R1C solver is known to
    // over-damp (see Issue #908).
    assert!(
        swing_reduction_pct >= 10.0,
        "900FF swing reduction ({:.1}%) should be ≥10% vs 600FF",
        swing_reduction_pct
    );
}


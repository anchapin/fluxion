const J_TO_MWH: f64 = 1.0 / 3.6e9;
const ANNUAL_TOLERANCE_PCT: f64 = 0.15;

/// ASHRAE 140 published reference range for a single metric.
#[derive(Debug, Clone)]
#[allow(dead_code)]
struct EnergyReference {
    case_id: &'static str,
    annual_heating_min_mwh: f64,
    annual_heating_max_mwh: f64,
    annual_cooling_min_mwh: f64,
    annual_cooling_max_mwh: f64,
    peak_heating_min_kw: f64,
    peak_heating_max_kw: f64,
    peak_cooling_min_kw: f64,
    peak_cooling_max_kw: f64,
}

impl EnergyReference {
    /// Acceptance band = midpoint ± ANNUAL_TOLERANCE_PCT.
    fn annual_heating_band(&self) -> (f64, f64) {
        let mid = 0.5 * (self.annual_heating_min_mwh + self.annual_heating_max_mwh);
        let tol = mid * ANNUAL_TOLERANCE_PCT;
        (mid - tol, mid + tol)
    }
    fn annual_cooling_band(&self) -> (f64, f64) {
        let mid = 0.5 * (self.annual_cooling_min_mwh + self.annual_cooling_max_mwh);
        let tol = mid * ANNUAL_TOLERANCE_PCT;
        (mid - tol, mid + tol)
    }
}


/// `MockSurfaceHeatFluxProvider` must be substitutable for the physics
/// provider at the trait-object level, and the zone solver should accept
/// pre-computed surface fluxes via this interface.
#[test]
fn test_mock_surface_flux_provider_trait_object_compatible() {
    // Two surfaces with non-zero fluxes
    let provider: Box<dyn SurfaceHeatFluxProvider> =
        Box::new(MockSurfaceHeatFluxProvider::new(vec![15.0, -10.0, 20.0]));

    assert_eq!(provider.num_surfaces(), 3);
    assert_eq!(provider.surface_heat_flux(0, 20.0, 5.0, 3600.0), 15.0);
    assert_eq!(provider.surface_heat_flux(1, 20.0, 5.0, 3600.0), -10.0);
    assert_eq!(provider.surface_heat_flux(2, 20.0, 5.0, 3600.0), 20.0);
    // Out-of-bounds
    assert_eq!(provider.surface_heat_flux(99, 20.0, 5.0, 3600.0), 0.0);
    // Name sanity
    assert!(!provider.name().is_empty());
}

/// `PhysicsSurfaceFluxProvider` should return Fourier-law heat flux
/// (Q = ΔT / R_total) for steady-state conditions, in the same units as
/// the `MockSurfaceHeatFluxProvider` ([W/m²] positive = into zone).
#[test]
fn test_physics_surface_flux_provider_steady_state() {
    let wall = WallSpec::single_layer("200mm Concrete", 0.2, 1.73, 2243.0, 837.0);
    let r_total = wall.total_r_value();

    let mut solver = FiveR1CSolver::new();
    solver.initialize(&wall).expect("5R1C init");

    let provider = PhysicsSurfaceFluxProvider::new()
        .add_surface(solver, /* area */ 1.0, /* solar_wm2 */ 0.0);

    assert_eq!(provider.num_surfaces(), 1);

    // Heat loss scenario: T_zone > T_outdoor → flux should be negative
    let q = provider.surface_heat_flux(0, 20.0, 0.0, 3600.0);
    let expected = (0.0 - 20.0) / r_total;
    let rel_error = ((q - expected) / expected).abs();

    println!(
        "[#1013 SFP] Q_actual={q:.4}, Q_expected={expected:.4}, rel_err={:.4}%",
        rel_error * 100.0
    );

    assert!(
        rel_error < STEADY_STATE_REL_TOL,
        "PhysicsSurfaceFluxProvider rel_error {rel_error} exceeds {STEADY_STATE_REL_TOL}"
    );
    assert!(q < 0.0, "Heat loss scenario: flux should be negative");
}

/// Verifies that the surface heat flux from `PhysicsSurfaceFluxProvider`
/// plus a constant internal gain produces the same energy balance as
/// the equivalent 5R1C step plus the internal gain. This is the trait
/// integration smoke test for the zone heat balance.
#[test]
fn test_surface_flux_provider_plus_loads_energy_balance() {
    let wall = WallSpec::single_layer("200mm Concrete", 0.2, 1.73, 2243.0, 837.0);
    let r_total = wall.total_r_value();

    let mut solver = FiveR1CSolver::new();
    solver.initialize(&wall).expect("5R1C init");

    let provider = PhysicsSurfaceFluxProvider::new().add_surface(solver, 1.0, 0.0);

    // Heat flux at steady state: T_zone=20, T_out=5 → heat loss → negative flux
    let q_provider = provider.surface_heat_flux(0, 20.0, 5.0, 3600.0);
    let q_5r1c = (5.0 - 20.0) / r_total;

    // Both should agree (sign convention: positive = into zone)
    let diff = (q_provider - q_5r1c).abs();
    assert!(
        diff < 1e-9,
        "Provider flux {q_provider} and 5R1C flux {q_5r1c} differ by {diff}"
    );

    // Conduction loss dominates; the zone solver must compensate via HVAC.
    // We verify the sign: net = conduction_loss + internal_gain.
    // With internal_gain < |q_provider|, net is still negative (HVAC heating needed).
    let internal_gain_w = 5.0; // small internal gain
    let net_heat_balance = q_provider + internal_gain_w;
    assert!(
        net_heat_balance < 0.0,
        "Net heat balance should be negative (heat loss dominates) — got {net_heat_balance}"
    );

    // With enough internal gain to overcome conduction, the sign flips.
    let large_internal_gain = q_provider.abs() + 1.0;
    let net_with_large_gain = q_provider + large_internal_gain;
    assert!(
        net_with_large_gain > 0.0,
        "Net heat balance with large internal gain should be positive — got {net_with_large_gain}"
    );
}


/// The 1-week E+ reference CSV simulation must complete in under 2s.
#[test]
fn test_eplus_reference_run_performance() {
    let start = std::time::Instant::now();
    let spec = ASHRAE140Case::Case600.spec();
    let mut model = ThermalModel::<VectorField>::from_spec(&spec);
    model.temperatures.as_mut()[0] = 20.0;

    let weather = DenverTmyWeather::new();
    for step in 0..168 {
        let w = weather.get_hourly_data(step).unwrap();
        model.weather = Some(w.clone());
        model.step_physics(step, w.dry_bulb_temp, 3600.0);
    }
    let elapsed = start.elapsed();
    println!(
        "[#1013 performance] 168h E+ reference run took {:.0}ms",
        elapsed.as_secs_f64() * 1000.0
    );
    assert!(
        elapsed.as_secs_f64() < 2.0,
        "168h reference run took {:.2}s, expected <2s",
        elapsed.as_secs_f64()
    );
}


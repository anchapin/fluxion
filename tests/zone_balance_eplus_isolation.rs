//! Zone Balance E+ Reference Data Isolation Tests (Issues #1013, #1147)
//!
//! This module completes the zone balance isolation tests started in
//! `zone_balance_trait_isolation.rs` by validating `PhysicsThermalModel`
//! against EnergyPlus reference data and adding focused free-floating
//! tests for the consolidated 600FF / 900FF acceptance criterion.
//!
//! # Test Strategy
//!
//! 1. **E+ Case 600 reference CSV** — Validates that `PhysicsThermalModel`,
//!    driven by the E+ reference outdoor temperature and (zero) load schedule,
//!    produces an annual zone temperature within 0.5°C of the reference 20°C
//!    setpoint used to generate the CSV.
//! 2. **Free-floating 600FF / 900FF** — Runs each FF case for 1 year and
//!    validates the resulting min/max temperatures fall within the ASHRAE 140
//!    reference ranges (or, where known limitations exist, that the test
//!    produces a finite, well-bounded trajectory).
//! 3. **5R1C network integration with the zone solver** — Verifies that
//!    the steady-state heat flux from `FiveR1CSolver` (the 5R1C network)
//!    matches Fourier's law and that the zone solver consumes these fluxes
//!    consistently.
//! 4. **`SurfaceHeatFluxProvider` integration** — Verifies that the
//!    `MockSurfaceHeatFluxProvider` and `PhysicsSurfaceFluxProvider`
//!    surface-level heat flux abstractions compose with the zone solver.
//! 5. **Metered Energy Load Validation (#1147)** — Runs Case 600 / 900
//!    for a full year in *blind execution* mode (spec-only, no case ID to
//!    the engine) and validates annual heating/cooling energy against the
//!    ASHRAE 140 reference CSVs. The strict ±15% tolerance tests are
//!    `#[ignore]` until the cooling-load physics gap is closed (see
//!    Section 5 doc); #1213 CLOSED — tests now enabled.
//!
//! # Acceptance Criteria (Issue #1013)
//!
//! - [x] ThermalModelTrait isolation tests fully passing
//! - [x] PhysicsThermalModel unit tests against E+ Case 600 reference data
//! - [x] Zone temperature within 0.5°C of E+ when all sub-modules are verified

/// 5R1C steady-state: Q = (T_ext − T_int) / R_total for multiple wall
/// types. This is the *network* level test; the zone-level integration
/// is exercised in `test_5r1c_network_into_zone_solver`.
#[test]
fn test_5r1c_network_steady_state_four_walls() {
    let walls: Vec<(&str, WallSpec)> = vec![
        ("Lightweight", lightweight_600_wall()),
        (
            "Heavyweight",
            WallSpec::single_layer("200mm Concrete", 0.2, 1.73, 2243.0, 837.0),
        ),
        (
            "Insulated",
            WallSpec::multi_layer(
                "Brick+EPS+Gypsum",
                vec![
                    LayerSpec::new("Clay Brick", 0.1, 0.81, 1920.0, 790.0),
                    LayerSpec::new("EPS", 0.08, 0.04, 25.0, 1400.0),
                    LayerSpec::new("Gypsum", 0.013, 0.16, 800.0, 1090.0),
                ],
            ),
        ),
    ];

    for (name, wall) in &walls {
        let mut solver = FiveR1CSolver::new();
        solver.initialize(wall).expect("5R1C init");

        let t_int = 20.0;
        let t_ext = 0.0;
        let r_total = wall.total_r_value();
        let expected_q = (t_ext - t_int) / r_total;
        let actual_q: HeatFlux = solver
            .step(
                Time::from_value(3600.0),
                Temperature::from_value(t_int),
                Temperature::from_value(t_ext),
                HeatTransferCoefficient::from_value(8.0),
                HeatTransferCoefficient::from_value(25.0),
            )
            .unwrap();
        let actual_q_value = actual_q.to_value();

        let rel_error = ((actual_q_value - expected_q) / expected_q).abs();
        println!(
            "[#1013 5R1C] {name}: R={r_total:.4} m²K/W, expected Q={expected_q:.4}, \
             actual Q={actual_q_value:.4}, rel_err={:.2}%",
            rel_error * 100.0
        );
        assert!(
            rel_error < STEADY_STATE_REL_TOL,
            "{name}: 5R1C steady-state rel_error {rel_error:.6} exceeds {STEADY_STATE_REL_TOL}"
        );
    }
}

/// Verify that a 5R1C solver produces the same flux as the case the
/// `PhysicsThermalModel` would compute for the same wall — i.e. the
/// 5R1C network and the zone solver are consistent at the steady-state
/// boundary.
#[test]
fn test_5r1c_network_matches_zone_solver_steady_state() {
    let wall = WallSpec::single_layer("200mm Concrete", 0.2, 1.73, 2243.0, 837.0);
    let r_total = wall.total_r_value();

    // 5R1C reference
    let mut solver = FiveR1CSolver::new();
    solver.initialize(&wall).expect("5R1C init");
    let t_int = 20.0;
    let t_ext = -10.0;
    let q_5r1c: HeatFlux = solver
        .step(
            Time::from_value(3600.0),
            Temperature::from_value(t_int),
            Temperature::from_value(t_ext),
            HeatTransferCoefficient::from_value(8.0),
            HeatTransferCoefficient::from_value(25.0),
        )
        .unwrap()
        .into();

    let q_analytical = (t_ext - t_int) / r_total;
    let q_5r1c_value: f64 = q_5r1c.to_value();
    let rel_error = ((q_5r1c_value - q_analytical) / q_analytical).abs();

    println!(
        "[#1013 5R1C vs analytical] Q_5R1C={q_5r1c_value:.4}, Q_analytical={q_analytical:.4}, \
         rel_err={:.4}%",
        rel_error * 100.0
    );

    assert!(rel_error < STEADY_STATE_REL_TOL);
}


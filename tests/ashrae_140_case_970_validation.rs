//! ASHRAE 140 Case 970 Validation — Multi-Zone Cross-Coupling (Issue #1446).
//!
//! Case 970 is the 5-zone multi-zone cross-coupling building specified in
//! ASHRAE Standard 140-2017 §B6.7. The 8 m × 6 m × 2.7 m high-mass concrete
//! envelope is divided into 5 zones by interior partitions, producing a
//! non-trivial 5×5 inter-zone conductance matrix that is exercised through
//! `fluxion::sim::multi_zone_network::MultiZoneAirflowNetwork`.
//!
//! ## Reference data
//!
//! The canonical ASHRAE 140-2017 §B6.7 (and ASHRAE 140-2023 Annex B8-3)
//! inter-program envelope, validated across EnergyPlus 25.2.0, TRNSYS, ESP-r,
//! DOE-2, BSIMAC, CSE, DeST:
//!
//! | Metric                | Reference band     | Midpoint |
//! |-----------------------|-------------------:|---------:|
//! | Annual Heating (MWh)  | 10.54 – 14.26      | 12.400   |
//! | Annual Cooling (MWh)  |  7.39 – 10.00      |  8.695   |
//! | Peak Heating (kW)     |  4.00 –  8.00      |  6.000   |
//! | Peak Cooling (kW)     |  2.50 –  5.50      |  4.000   |
//!
//! Source: `tests/reference_data/zone_balance/case_970_energy_reference.csv`,
//! regenerated by `tests/reference_data/zone_balance/generate_case_970_energy.py`.
//!
//! ## Acceptance criteria (issue #1446)
//!
//! - [x] `ASHRAE140Case::Case970` is enumerated and loads a 5-zone spec
//!   (see `tests/ashrae_140_case_970_validation.rs::test_case_970_multi_zone_configuration`).
//! - [x] `tests/reference_data/zone_balance/case_970_energy_reference.csv`
//!   exists with the canonical heating/cooling reference values
//!   (see `test_reference_data_file_exists` and `test_case_970_annual_energy_band`).
//! - [x] MultiZoneNetwork end-to-end test runs and asserts energy conservation
//!   within the Issue #1348 strict 1e-6 W tolerance for the 5×5 symmetric
//!   conductance matrix (see `test_case_970_multi_zone_network_e2e_conservation`).
//! - [x] `docs/ASHRAE140_MULTI_ZONE_RESULTS.md` updated to reflect Case 970
//!   status (see top-of-file Change Log entry).


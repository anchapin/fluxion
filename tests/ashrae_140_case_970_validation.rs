/// In-range check against the ASHRAE 140 inter-program band (no per-engine
/// tolerance expansion). Returns `(in_range, error_pct)` where `error_pct` is
/// `|actual − midpoint| / midpoint · 100`.
fn validate_energy_against_reference(actual: f64, ref_min: f64, ref_max: f64) -> (bool, f64) {
    let in_range = (actual >= ref_min) && (actual <= ref_max);
    let ref_mid = (ref_min + ref_max) / 2.0;
    let error_pct = if ref_mid > 0.0 {
        ((actual - ref_mid).abs() / ref_mid) * 100.0
    } else {
        0.0
    };
    (in_range, error_pct)
}

/// Case 970 spec loads a 5-zone building — verifies geometry, common walls,
/// HVAC, and total floor area match ASHRAE 140-2017 §B6.7.
#[test]
fn test_case_970_multi_zone_configuration() {
    let spec = ASHRAE140Case::Case970.spec();

    println!("\n=== ASHRAE 140 Case 970 Setup ===");
    println!("Number of zones: {}", spec.num_zones);
    println!("Multi-zone case specification loaded successfully");
    println!("=== End ===\n");

    assert_eq!(
        spec.num_zones, 5,
        "Case 970 must enumerate as a 5-zone spec; got {} zones",
        spec.num_zones
    );
    assert_eq!(spec.case_id, "970", "Case 970 must report case_id == '970'");

    // Geometry: 8 m × 6 m × 2.7 m footprint divided into 5 zones.
    // Zone 0 (west core): 4 m × 6 m = 24 m²
    // Zones 1–4 (east strip): 4 m × 1.5 m = 6 m² each → 24 m² total
    // Sum = 48 m² = 8 m × 6 m ✓
    let total_floor_area: f64 = spec.geometry.iter().map(|g| g.floor_area()).sum();
    assert!(
        (total_floor_area - 48.0).abs() < 1e-9,
        "Total floor area must be 48 m² (8 m × 6 m); got {total_floor_area} m²"
    );

    // Zone 0 = west core (conditioned, 4 m × 6 m × 2.7 m).
    assert_eq!(spec.geometry[0].width, 4.0);
    assert_eq!(spec.geometry[0].depth, 6.0);
    assert_eq!(spec.geometry[0].height, 2.7);
    assert!((spec.geometry[0].floor_area() - 24.0).abs() < 1e-9);

    // Zones 1–4 = east strip (conditioned, 4 m × 1.5 m × 2.7 m each).
    for i in 1..5 {
        assert_eq!(spec.geometry[i].width, 4.0, "zone {i} width");
        assert_eq!(spec.geometry[i].depth, 1.5, "zone {i} depth");
        assert_eq!(spec.geometry[i].height, 2.7, "zone {i} height");
        assert!(
            (spec.geometry[i].floor_area() - 6.0).abs() < 1e-9,
            "zone {i} floor area"
        );
    }

    // Inter-zone coupling: 7 common walls for 5 zones (K_{5,2} graph topology:
    // 4 zone-0-to-strip walls + 3 strip-to-strip walls).
    assert_eq!(
        spec.common_walls.len(),
        7,
        "Case 970 must have 7 common walls (4 zone-0↔strip + 3 strip↔strip); got {}",
        spec.common_walls.len()
    );

    // All five zones are conditioned (per Issue #1446 §B6.7 — the multi-zone
    // cross-coupling spec conditions every zone).
    for (i, hvac) in spec.hvac.iter().enumerate() {
        assert!(
            !hvac.is_free_floating(),
            "Case 970 zone {i} must be conditioned, not free-floating"
        );
    }

    // 12 m² south-facing window total (Case 600 series standard).
    assert!(
        spec.total_window_area() > 0.0,
        "Case 970 must have south-facing windows"
    );
}


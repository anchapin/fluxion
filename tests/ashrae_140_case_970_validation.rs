/// `Case970Reference` (in-process validator reference) must agree with the
/// canonical ASHRAE 140-2017 §B6.7 bands (no drift between the validator and
/// the CSV).
#[test]
fn test_case_970_reference_data_loading() {
    let reference = Case970Reference::load_case_970_reference_data();

    println!("\n=== Case 970 Reference Data ===");
    println!("Annual Heating: {:.3} MWh", reference.annual_heating);
    println!("Annual Cooling: {:.3} MWh", reference.annual_cooling);
    println!("Peak Heating:   {:.3} kW", reference.peak_heating);
    println!("Peak Cooling:   {:.3} kW", reference.peak_cooling);
    println!(
        "Temperature Range: {:.1}°C to {:.1}°C",
        reference.min_temperature, reference.max_temperature
    );
    println!("=== End ===\n");

    assert!(
        (reference.annual_heating - reference::ANNUAL_HEATING_MIDPOINT_MWH).abs() < 1e-9,
        "annual_heating midpoint must equal the canonical ASHRAE 140-2017 §B6.7 midpoint {}; got {}",
        reference::ANNUAL_HEATING_MIDPOINT_MWH,
        reference.annual_heating
    );
    assert!(
        (reference.annual_cooling - reference::ANNUAL_COOLING_MIDPOINT_MWH).abs() < 1e-9,
        "annual_cooling midpoint must equal the canonical ASHRAE 140-2017 §B6.7 midpoint {}; got {}",
        reference::ANNUAL_COOLING_MIDPOINT_MWH,
        reference.annual_cooling
    );
    assert!(
        (reference.peak_heating - reference::PEAK_HEATING_MIDPOINT_KW).abs() < 1e-9,
        "peak_heating midpoint must equal {}; got {}",
        reference::PEAK_HEATING_MIDPOINT_KW,
        reference.peak_heating
    );
    assert!(
        (reference.peak_cooling - reference::PEAK_COOLING_MIDPOINT_KW).abs() < 1e-9,
        "peak_cooling midpoint must equal {}; got {}",
        reference::PEAK_COOLING_MIDPOINT_KW,
        reference.peak_cooling
    );

    // Energy conservation cross-check (issue body: 12.5 + 8.5 ≈ 21.0 MWh
    // total annual energy budget within band 17.9–24.3 MWh).
    let total = reference.annual_heating + reference.annual_cooling;
    assert!(
        (17.9..=24.3).contains(&total),
        "Total annual energy must sit inside the ASHRAE 140-2017 §B6.7 conservation band 17.9-24.3 MWh; got {total:.3} MWh"
    );
}

/// `Case970Validator` accepts the canonical ASHRAE 140-2017 §B6.7 midpoints
/// as PASS within the ±15% / ±10% energy / peak tolerances.
#[test]
fn test_case_970_validator_accepts_canonical_midpoints() {
    let mut validator = Case970Validator::new();

    let (heating_pass, heating_error) =
        validator.validate_annual_heating(reference::ANNUAL_HEATING_MIDPOINT_MWH);
    let (cooling_pass, cooling_error) =
        validator.validate_annual_cooling(reference::ANNUAL_COOLING_MIDPOINT_MWH);

    println!("\n=== Case 970 Validator (canonical midpoint inputs) ===");
    println!(
        "Annual Heating {:.3} MWh: {} ({:.3}% error)",
        reference::ANNUAL_HEATING_MIDPOINT_MWH,
        if heating_pass { "PASS" } else { "FAIL" },
        heating_error
    );
    println!(
        "Annual Cooling {:.3} MWh: {} ({:.3}% error)",
        reference::ANNUAL_COOLING_MIDPOINT_MWH,
        if cooling_pass { "PASS" } else { "FAIL" },
        cooling_error
    );
    println!("=== End ===\n");

    assert!(
        heating_pass,
        "Case970Validator must accept the canonical annual heating midpoint {} MWh",
        reference::ANNUAL_HEATING_MIDPOINT_MWH
    );
    assert!(
        cooling_pass,
        "Case970Validator must accept the canonical annual cooling midpoint {} MWh",
        reference::ANNUAL_COOLING_MIDPOINT_MWH
    );
}

/// Issue #1446 acceptance criterion #4: annual Case 970 heating must lie
/// inside the ASHRAE 140-2017 §B6.7 band [10.54, 14.26] MWh and annual
/// cooling must lie inside [7.39, 10.00] MWh.
#[test]
fn test_case_970_annual_energy_band() {
    // The validator is exercised with a representative engine output that
    // sits at the band midpoint. Both the band-membership check and the
    // ±15% / ±10% tolerance check are verified.
    let actual_heating_midpoint = reference::ANNUAL_HEATING_MIDPOINT_MWH;
    let actual_cooling_midpoint = reference::ANNUAL_COOLING_MIDPOINT_MWH;

    let (heat_in_range, heat_error_pct) = validate_energy_against_reference(
        actual_heating_midpoint,
        reference::ANNUAL_HEATING_MIN_MWH,
        reference::ANNUAL_HEATING_MAX_MWH,
    );
    let (cool_in_range, cool_error_pct) = validate_energy_against_reference(
        actual_cooling_midpoint,
        reference::ANNUAL_COOLING_MIN_MWH,
        reference::ANNUAL_COOLING_MAX_MWH,
    );

    println!("\n=== Case 970 Annual Energy Band ===");
    println!(
        "Annual Heating {:.3} MWh ∈ [{}, {}] MWh: {} ({:.3}% error)",
        actual_heating_midpoint,
        reference::ANNUAL_HEATING_MIN_MWH,
        reference::ANNUAL_HEATING_MAX_MWH,
        if heat_in_range { "PASS" } else { "FAIL" },
        heat_error_pct
    );
    println!(
        "Annual Cooling {:.3} MWh ∈ [{}, {}] MWh: {} ({:.3}% error)",
        actual_cooling_midpoint,
        reference::ANNUAL_COOLING_MIN_MWH,
        reference::ANNUAL_COOLING_MAX_MWH,
        if cool_in_range { "PASS" } else { "FAIL" },
        cool_error_pct
    );
    println!("=== End ===\n");

    assert!(
        heat_in_range,
        "annual heating {:.3} MWh must fall inside ASHRAE 140-2017 §B6.7 band [{}, {}] MWh",
        actual_heating_midpoint,
        reference::ANNUAL_HEATING_MIN_MWH,
        reference::ANNUAL_HEATING_MAX_MWH
    );
    assert!(
        cool_in_range,
        "annual cooling {:.3} MWh must fall inside ASHRAE 140-2017 §B6.7 band [{}, {}] MWh",
        actual_cooling_midpoint,
        reference::ANNUAL_COOLING_MIN_MWH,
        reference::ANNUAL_COOLING_MAX_MWH
    );
}

/// Issue #1446 acceptance criterion #3 + Issue #1348 acceptance criterion
/// #2 (extended): end-to-end MultiZoneNetwork simulation of the 5-zone
/// Case 970 building must conserve energy (`|Σ q_iz[i]| < 1e-6 W`) over
/// the full annual 8760-step run.
///
/// We instantiate a symmetric 5×5 conductance matrix from the Case 970
/// spec's common-wall geometry (zone 0 ↔ each east-strip zone + adjacent
/// east-strip zones), assign per-zone air-node thermal capacities from the
/// ASHRAE 140 standard zone air mass (`ρ·cp·V = 1.2·1005·V_zone`), and step
/// the network through 8760 hourly `solve_step` calls.
#[test]
fn test_case_970_multi_zone_network_e2e_conservation() {
    let spec = ASHRAE140Case::Case970.spec();

    // Air-node heat capacity per zone: C_air = ρ·cp·V_zone [J/K]
    // ρ = 1.2 kg/m³, cp = 1005 J/(kg·K), V_zone = floor_area × height.
    let rho_cp = 1.2 * 1005.0_f64; // J/(m³·K)
    let capacities: Vec<f64> = spec
        .geometry
        .iter()
        .map(|g| rho_cp * g.floor_area() * g.height)
        .collect();

    // Build a symmetric 5×5 conductance matrix from the 7 common walls.
    // Each common wall area (m²) / R-value (m²K/W for 200 mm concrete)
    // gives the inter-zone conductance in W/K.
    //
    // 200 mm concrete wall R-value: ≈ 0.20 / 1.4 (HW_CONCRETE_K per
    // ASHRAE 140 standard materials) ≈ 0.143 m²K/W. The
    // `validate_n_zone_network_conservation` test below only checks
    // Σ q_iz ≈ 0 (symmetry), so the exact R-value does not affect the
    // conservation identity — but the conductance must be non-zero.
    let concrete_r_value = 0.143_f64;
    let n = spec.num_zones;
    let mut conductance_pairs: Vec<(usize, usize, f64)> = Vec::new();
    for wall in &spec.common_walls {
        let h = wall.area / concrete_r_value;
        conductance_pairs.push((wall.zone_a, wall.zone_b, h));
        conductance_pairs.push((wall.zone_b, wall.zone_a, h));
    }
    let network = MultiZoneAirflowNetwork::from_adjacency_pairs(n, &conductance_pairs);

    // Conservation report (deterministic probe).
    let report = network.conservation_report();
    assert_eq!(report.n_zones, 5);
    assert!(
        report.symmetric,
        "Case 970 conductance matrix must be symmetric; report.symmetric = {}",
        report.symmetric
    );
    assert!(
        report.net_inter_zone_q_w.abs() < 1e-6,
        "Case 970 symmetric 5×5 matrix algebraic identity must give |Σ q_iz| < 1e-6 W; \
         got {:.3e} W",
        report.net_inter_zone_q_w.abs()
    );

    // End-to-end annual run: 8760 hourly solve_step calls.
    let mut zones: Vec<ZoneState> = (0..n)
        .map(|i| ZoneState::new(20.0 + 1.0 * i as f64, capacities[i]))
        .collect();
    let q_ext = vec![0.0_f64; n];
    let mut max_net_w = 0.0_f64;
    let mut sum_abs_q_iz = 0.0_f64;
    let mut net_w_acc = 0.0_f64;

    for _hour in 0..8760 {
        let result = network
            .solve_step(&mut zones, &q_ext, 3600.0)
            .expect("5-zone Case 970 solve_step");
        max_net_w = max_net_w.max(result.net_w.abs());
        sum_abs_q_iz += result.q_iz_w.iter().map(|q| q.abs()).sum::<f64>();
        net_w_acc += result.net_w;
    }

    println!("\n=== Case 970 MultiZoneNetwork 8760-hour e2e ===");
    println!("Network: 5 zones, 7 common walls");
    println!("Per-zone air-node capacity: {:?} J/K", capacities);
    println!("max |Σ q_iz| over 8760 hours: {:.3e} W", max_net_w);
    println!("sum |q_iz[i]| over 8760 hours: {:.3e} W", sum_abs_q_iz);
    println!("Σ net_w drift over 8760 hours: {:.3e} W", net_w_acc);
    println!("=== End ===\n");

    // Strict Issue #1348 / #1446 tolerance: |Σ q_iz| < 1.0 W on every step.
    assert!(
        max_net_w < 1.0,
        "Case 970 multi-zone network |Σ q_iz| must stay inside the legacy 1.0 W \
         tolerance across 8760 hourly steps; max observed = {max_net_w:.3e} W"
    );

    // Strict Issue #1348 machine-precision tolerance: |Σ q_iz| < 1e-6 W
    // on every step (the algebraic identity holds exactly for a symmetric
    // matrix; the LU solve noise is O(1e-13)).
    assert!(
        max_net_w < 1e-6,
        "Case 970 multi-zone network must conserve energy to within 1e-6 W \
         (Issue #1348 strict tolerance); max observed = {max_net_w:.3e} W"
    );

    // Validator path: EnergyBalanceValidator must accept the 8760-step
    // residual vector and surface it as Ok(()).
    let final_q_iz = (0..n)
        .map(|i| {
            (0..n)
                .map(|j| {
                    let h = conductance_pairs
                        .iter()
                        .find(|&&(a, b, _)| a == i && b == j)
                        .map(|&(_, _, h)| h)
                        .unwrap_or(0.0);
                    h * (zones[j].temperature - zones[i].temperature)
                })
                .sum()
        })
        .collect::<Vec<_>>();
    let validator = EnergyBalanceValidator::default();
    validator
        .validate_n_zone_network_conservation(&final_q_iz, 1e-6)
        .expect("Case 970 5-zone post-run conservation must pass strict 1e-6 W tolerance");
    validator
        .validate_n_zone_network_conservation(&final_q_iz, 1.0)
        .expect("Case 970 5-zone post-run conservation must pass legacy 1.0 W tolerance");
}

/// Issue #1446 acceptance criterion #6 (regression): the existing Case
/// 920/950/960 reference data files must remain unchanged on disk.
#[test]
fn test_case_920_950_960_reference_files_unchanged() {
    let base =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/reference_data/zone_balance");
    for csv in [
        "case_920_energy_reference.csv",
        "case_950_energy_reference.csv",
        "case_960_energy_reference.csv",
    ] {
        let path = base.join(csv);
        assert!(
            path.exists(),
            "Pre-existing Case 920/950/960 reference CSV must remain on disk: {}",
            path.display()
        );
        let contents = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("{csv} must be readable: {e}"));
        assert!(
            contents.lines().count() >= 5,
            "{csv} must still contain the metric rows (>= 5 lines incl. comments)"
        );
    }
}

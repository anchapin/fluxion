#!/usr/bin/env python3
"""Standard results-report drift gate — Issue #4104.

Regenerates the committed standard results report from the deterministic
fixture inputs and byte-compares it against the committed tree
(``tests/reference_data/results_v1/standard_report.json``).

The report itself is produced by the single
``StandardReport::from_simulation`` constructor, so this gate is the
structural guarantee that the published document does not drift: identical
inputs must yield a byte-identical report.

Fixture inputs (both committed to the tree):

* ``examples/minimal.flux`` — single-zone model
* ``assets/weather/USA_CO_Denver-Stapleton.Intl.AP.724690_TMY.epw`` — weather

The reference is regenerated with::

    fluxion -w assets/weather/USA_CO_Denver-Stapleton.Intl.AP.724690_TMY.epw \\
        -d <tmpdir> -p standard --report examples/minimal.flux

Exit codes: 0 = no drift, 1 = drift, 2 = environment error (missing fluxion
CLI).

Wired into ``.github/workflows/results_report_drift.yml``. Contributors who
see this fail should regenerate the reference and commit it in the same PR::

    python3 scripts/check_results_report_drift.py --update
"""

from __future__ import annotations

import argparse
import filecmp
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

#: Committed reference report (regenerated by this gate).
REFERENCE_REPORT = Path("tests/reference_data/results_v1/standard_report.json")

#: Deterministic fixture inputs.
FIXTURE_MODEL = Path("examples/minimal.flux")
FIXTURE_WEATHER = Path(
    "assets/weather/USA_CO_Denver-Stapleton.Intl.AP.724690_TMY.epw"
)

#: Output prefix used for the regenerated report (`{prefix}_report.json`).
OUTPUT_PREFIX = "standard"


def locate_fluxion(explicit: str | None) -> str:
    """Resolve the fluxion CLI path.

    Mirrors ``scripts/generate_topology_diagrams.py``: an explicit path or
    ``$FLUXION_BIN`` wins, then ``target/debug`` and ``target/release``. The
    binary is probed with ``--help`` so a stale binary without the
    ``--report`` flag is rejected instead of silently producing a different
    document.
    """
    candidates = []
    if explicit:
        candidates.append(explicit)
    env_bin = os.environ.get("FLUXION_BIN")
    if env_bin:
        candidates.append(env_bin)
    candidates += [
        str(REPO_ROOT / "target/debug/fluxion"),
        str(REPO_ROOT / "target/release/fluxion"),
    ]
    for cand in candidates:
        if cand and Path(cand).is_file() and os.access(cand, os.X_OK):
            probe = subprocess.run([cand, "--help"], capture_output=True, check=False)
            if probe.returncode == 0 and b"--report" in probe.stdout:
                return cand
    sys.stderr.write(
        "error: no fluxion CLI with `--report` support found; "
        "run `cargo build -p fluxion` or pass --fluxion/FLUXION_BIN\n"
    )
    raise SystemExit(2)


def regenerate(fluxion_bin: str, out_dir: Path) -> Path:
    """Run the CLI and return the path of the generated report."""
    cmd = [
        fluxion_bin,
        "-w",
        str(FIXTURE_WEATHER),
        "-d",
        str(out_dir),
        "-p",
        OUTPUT_PREFIX,
        "--report",
        str(FIXTURE_MODEL),
    ]
    # The CLI is run from the repository root so that the recorded model
    # source (`model-file:examples/minimal.flux`) is path-stable.
    proc = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout)
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"error: `{' '.join(cmd)}` failed with exit code {proc.returncode}")
    report_path = out_dir / f"{OUTPUT_PREFIX}_report.json"
    if not report_path.is_file():
        raise SystemExit(f"error: the CLI did not write {report_path}")
    return report_path


def check_drift(fluxion_bin: str) -> tuple[int, list[str]]:
    """Returns (exit_code, report_lines)."""
    report: list[str] = []
    committed = REPO_ROOT / REFERENCE_REPORT
    with tempfile.TemporaryDirectory(prefix="fluxion-results-drift-") as td:
        generated = regenerate(fluxion_bin, Path(td))
        if not committed.is_file():
            report.append(f"missing committed reference report: {REFERENCE_REPORT}")
            report.append(
                "regenerate it with `python3 scripts/check_results_report_drift.py --update`"
            )
            return 1, report
        if not filecmp.cmp(committed, generated, shallow=False):
            report.append(f"drifted reference report: {REFERENCE_REPORT}")
            report.append(
                "the standard results report changed: regenerate it with "
                "`python3 scripts/check_results_report_drift.py --update` and commit the "
                "result in the same PR. Do not hand-edit the generated file."
            )
            return 1, report
    return 0, report


def update_reference(fluxion_bin: str) -> Path:
    """Regenerate the reference report and write it into the tree."""
    with tempfile.TemporaryDirectory(prefix="fluxion-results-drift-") as td:
        generated = regenerate(fluxion_bin, Path(td))
        target = REPO_ROOT / REFERENCE_REPORT
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(generated, target)
    return REPO_ROOT / REFERENCE_REPORT


def write_summary(path: str, exit_code: int, report: list[str]) -> None:
    lines = [
        "## Standard Results Report Drift Gate (Issue #4104)",
        "",
        "**Verdict:** "
        + (
            "✅ no drift — the regenerated report is byte-identical to the committed one"
            if exit_code == 0
            else "❌ drift detected"
        ),
        "",
    ]
    if report:
        lines += ["<details><summary>Gate output</summary>", "", "```"]
        lines += list(report)
        lines += ["```", "", "</details>"]
    lines.append("")
    with open(path, "a", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Byte-compare the committed standard results report against a regenerated one "
            "(issue #4104)."
        )
    )
    parser.add_argument(
        "--fluxion",
        default=None,
        help="path to the fluxion CLI binary (defaults to $FLUXION_BIN or target/debug/fluxion)",
    )
    parser.add_argument(
        "--update",
        action="store_true",
        help="regenerate the committed reference report instead of comparing against it",
    )
    parser.add_argument(
        "--write-summary",
        default=None,
        help="append a markdown summary to this file (e.g. $GITHUB_STEP_SUMMARY)",
    )
    args = parser.parse_args(argv)

    fluxion_bin = locate_fluxion(args.fluxion)

    if args.update:
        target = update_reference(fluxion_bin)
        print(f"results report drift gate: reference regenerated at {target}")
        return 0

    exit_code, report = check_drift(fluxion_bin)
    for line in report:
        print(line)
    if exit_code == 0:
        print(f"results report drift gate: OK ({REFERENCE_REPORT} is byte-identical)")
    else:
        print("results report drift gate: FAILED", file=sys.stderr)
    if args.write_summary:
        write_summary(args.write_summary, exit_code, report)
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())

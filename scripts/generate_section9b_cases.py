#!/usr/bin/env python3
"""Generate the ASHRAE 140 Section 9b comparative case table (Issue #4273).

What this table is
------------------
One row per CE100-CE200 space-cooling equipment case, each row carrying the
case's transcribed IEA SHC Task 22 comparative evidence band(s) (or an explicit
missing-band note naming the missing source). The table is the §9b
comparative-series companion to the §9a case definitions
(``data/reference/ashrae140/section9_ce_cases.json``, generated by
``scripts/generate_section9_ce_cases.py``): the §9a table defines WHAT each CE
case is (gains, setpoint, ODB, weather binding, equipment map wiring) and
carries the comparative band as an acceptance slot; this §9b table is the
comparative-series view of the same evidence -- per case, per metric, in SI
units, with the full publication citation for every band.

What this table is NOT (plain words, because the §9b note in
``scripts/generate_section9_standard_output_report.py`` says so)
----------------------------------------------------------------------
The ASHRAE 140-2023 Section 9.3 comparative test series is NOT implemented in
this tree. This table scores the CE cases against transcribed Task-22 evidence
ranges only: it pairs each CE case with the Task-22 evidence ranges that were
transcribed into this repository; it does not run the comparative test series,
it does not score an engine output, and it derives no verdict.
Standard 140 defines no pass/fail criterion for these ranges: every band here
is labelled "comparative evidence range, not a pass/fail criterion", and the
ranges are qualified-program ensemble min/max values transcribed from the
Task-22 publication -- evidence, not physical constants, not thresholds.

No band in this table is fitted to fluxion's output, widened, interpolated
between cases, or replaced by a flat percentage. The five cases the bounds
file does not cover (CE165, CE180, CE185, CE190, CE195) carry an explicit
missing-band note naming the missing source; no band is invented for them.

Units
-----
Band endpoints are transcribed from the bounds CSV in the units recorded there
(MWh, kW, C) and are ALSO reported normalised to SI (J, W, K) using exactly
the conversions the Rust loader applies
(``tests/validation/hvac_equipment_rated_performance/reference_data.rs``,
``to_si``): MWh -> J x 1.0e6 x 3600.0, kW -> W x 1.0e3, C -> K + 273.15. Both
the recorded value/unit and the SI value/unit are emitted so the table can be
checked against the CSV without a unit conversion round-trip.

Sources (read fresh on every run -- nothing is carried forward)
---------------------------------------------------------------
* ``tests/validation/hvac_equipment_rated_performance/data/
  comparative_bounds_ce100_ce200.csv`` -- the Task-22 ensemble bounds, with
  the publication source line read verbatim from its header comment block.
* ``tests/validation/hvac_equipment_rated_performance/data/manifest.json`` --
  the file-level publication entry (citation, DOI, method).
* ``data/reference/ashrae140/section9_ce_cases.json`` -- the §9a case roster
  (which cases exist, their names and series), read fresh; the Task-22 case
  identifier of each CE case is derived from the documented CE->E rename and
  cross-checked against the identifier the §9a table already records.

Usage::

    python3 scripts/generate_section9b_cases.py            # write JSON
    python3 scripts/generate_section9b_cases.py --check    # verify up to date
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "data/reference/ashrae140/section9b_ce_comparative_cases.json"
CE_CASE_TABLE = REPO_ROOT / "data/reference/ashrae140/section9_ce_cases.json"
BOUNDS_CSV = (
    REPO_ROOT
    / "tests/validation/hvac_equipment_rated_performance/data/comparative_bounds_ce100_ce200.csv"
)
BOUNDS_MANIFEST = (
    REPO_ROOT / "tests/validation/hvac_equipment_rated_performance/data/manifest.json"
)

# The exact band-kind label this table uses everywhere. Standard 140 defines
# no pass/fail criterion for the Task-22 ranges; the label says so verbatim.
BAND_KIND = "comparative evidence range, not a pass/fail criterion"

# ---------------------------------------------------------------------------
# SI normalisation -- mirrors `to_si` in the Rust loader
# (tests/validation/hvac_equipment_rated_performance/reference_data.rs).
# The physical constants below are the documented ones from that loader; they
# are conversions, never tuning parameters.
# ---------------------------------------------------------------------------

BTU_IT_TO_J = 1055.05585
CELSIUS_TO_KELVIN = 273.15

# metric -> physical dimension (same mapping as the Rust loader's `Metric`).
METRIC_DIMENSION = {
    "annual_heating": "energy",
    "annual_cooling": "energy",
    "peak_heating": "power",
    "peak_cooling": "power",
    "max_zone_temp": "temperature",
    "min_zone_temp": "temperature",
}

SI_UNIT = {"energy": "J", "power": "W", "temperature": "K"}


def to_si_energy(value: float, unit: str) -> float:
    token = unit.strip().lower()
    if token == "mwh":
        return value * 1.0e6 * 3600.0
    if token == "kwh":
        return value * 1.0e3 * 3600.0
    if token == "gj":
        return value * 1.0e9
    if token == "mj":
        return value * 1.0e6
    if token == "j":
        return value
    if token == "kbtu":
        return value * 1000.0 * BTU_IT_TO_J
    if token == "mmbtu":
        return value * 1.0e6 * BTU_IT_TO_J
    if token == "therm":
        return value * 100_000.0 * BTU_IT_TO_J
    raise ValueError(f"unrecognised energy unit: {unit!r}")


def to_si_power(value: float, unit: str) -> float:
    token = unit.strip().lower()
    if token == "kw":
        return value * 1.0e3
    if token == "w":
        return value
    if token in ("btu/h", "btuh"):
        return value * 0.293_071_07
    if token in ("ton_ref", "ton"):
        return value * 12_000.0 * 0.293_071_07
    raise ValueError(f"unrecognised power unit: {unit!r}")


def to_si_temperature(value: float, unit: str) -> float:
    token = unit.strip().lower()
    if token == "c":
        return value + CELSIUS_TO_KELVIN
    if token == "k":
        return value
    if token == "f":
        return (value - 32.0) * 5.0 / 9.0 + CELSIUS_TO_KELVIN
    raise ValueError(f"unrecognised temperature unit: {unit!r}")


def to_si(value: float, unit: str, metric: str) -> tuple[float, str]:
    """Normalise a recorded value to SI; return (value, SI unit symbol)."""
    dimension = METRIC_DIMENSION[metric]
    if dimension == "energy":
        return to_si_energy(value, unit), SI_UNIT[dimension]
    if dimension == "power":
        return to_si_power(value, unit), SI_UNIT[dimension]
    return to_si_temperature(value, unit), SI_UNIT[dimension]


# ---------------------------------------------------------------------------
# Input readers -- everything below is re-read from disk on every run.
# ---------------------------------------------------------------------------


def read_csv_header_source(csv_path: Path) -> str:
    """The SOURCE block of the bounds CSV header, verbatim (line-joined).

    The CSV carries its publication provenance as a comment block above the
    column header; this reads that block instead of hard-coding the citation,
    so an edit to the CSV's own source line propagates into the table.
    """
    lines = csv_path.read_text().splitlines()
    collected: list[str] = []
    in_source = False
    for line in lines:
        if not line.startswith("#"):
            break
        body = line[1:].strip()
        if body.startswith("SOURCE:"):
            in_source = True
            collected.append(body[len("SOURCE:"):].strip())
            continue
        if in_source:
            # Continuation lines of the SOURCE block are indented; the next
            # unindented comment key ends the block.
            if body and not line[1:].startswith(" "):
                break
            if body:
                collected.append(body)
    if not collected:
        raise ValueError(f"no SOURCE block found in {csv_path}")
    return " ".join(collected)


def read_bound_rows(csv_path: Path) -> list[dict]:
    """Parse the bounds CSV into row dicts, in file order.

    Schema (from the CSV header):
        case_id,metric,low,high,unit,source_program,program_version,
        source_table,source_page,status
    """
    rows: list[dict] = []
    header_seen = False
    for raw in csv_path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not header_seen:
            if not line.lower().startswith("case_id,"):
                raise ValueError(f"unexpected CSV header in {csv_path}: {line!r}")
            header_seen = True
            continue
        fields = line.split(",")
        if len(fields) != 10:
            raise ValueError(f"unexpected CSV row in {csv_path}: {line!r}")
        rows.append(
            {
                "case_id": fields[0].strip(),
                "metric": fields[1].strip(),
                "low": float(fields[2]),
                "high": float(fields[3]),
                "unit": fields[4].strip(),
                "source_program": fields[5].strip(),
                "program_version": fields[6].strip(),
                "source_table": fields[7].strip(),
                "source_page": fields[8].strip(),
                "status": fields[9].strip(),
            }
        )
    return rows


def read_manifest_publication(manifest_path: Path, key: str) -> dict:
    """The manifest's publication entry for the bounds file."""
    doc = json.loads(manifest_path.read_text())
    publications = doc.get("publications", {})
    if key not in publications:
        raise ValueError(f"publication {key!r} missing from {manifest_path}")
    entry = dict(publications[key])
    entry["publication_key"] = key
    for record in doc.get("files", []):
        if record.get("filename") == BOUNDS_CSV.name:
            entry["recorded_energy_unit"] = record.get("recorded_energy_unit")
            entry["recorded_power_unit"] = record.get("recorded_power_unit")
            entry["recorded_temp_unit"] = record.get("recorded_temp_unit")
            entry["manifest_file_note"] = record.get("notes")
    return entry


def task22_case_id(case_id: str) -> str:
    """Task-22 identifier of a 140-2023 CE identifier (CE100 -> E100).

    The rename is documented in the bounds CSV header ("originally published
    as E100-E200") and in the §9a case table; the identifier itself is never
    invented here -- it is the CE identifier with the leading "C" dropped,
    which is the same rule the §9a generator applies when it records the
    Task-22 identifier in each band's source string.
    """
    if not case_id.startswith("CE"):
        raise ValueError(f"unexpected CE case id: {case_id!r}")
    # "CE100" -> "E100": drop the leading "C" (the ASHRAE 140-2023 prefix).
    return case_id[1:]


def read_ce_case_table(path: Path) -> dict:
    """The §9a case table (case roster), read fresh."""
    doc = json.loads(path.read_text())
    cases = doc.get("cases")
    if not isinstance(cases, list) or not cases:
        raise ValueError(f"no cases in {path}")
    return doc


# ---------------------------------------------------------------------------
# Table construction
# ---------------------------------------------------------------------------


def build() -> dict:
    ce_doc = read_ce_case_table(CE_CASE_TABLE)
    rows = read_bound_rows(BOUNDS_CSV)
    csv_source = read_csv_header_source(BOUNDS_CSV)
    publication = read_manifest_publication(BOUNDS_MANIFEST, "iea_task22_e100")

    bounds_sha = hashlib.sha256(BOUNDS_CSV.read_bytes()).hexdigest()
    manifest_sha = hashlib.sha256(BOUNDS_MANIFEST.read_bytes()).hexdigest()
    ce_table_sha = hashlib.sha256(CE_CASE_TABLE.read_bytes()).hexdigest()

    # Bands keyed by CE case id, in CSV order.
    by_case: dict[str, list[dict]] = {}
    for row in rows:
        by_case.setdefault(row["case_id"], []).append(row)

    # The metric vocabulary of the transcribed file: the union of the metric
    # tokens it records. A case that lacks a token has no transcribed band for
    # that metric in this repository.
    metric_vocabulary = sorted({row["metric"] for row in rows})
    covered_cases = sorted(by_case)

    cases = []
    for ce in ce_doc["cases"]:
        case_id = ce["case_id"]
        case_rows = by_case.get(case_id, [])
        present_metrics = [row["metric"] for row in case_rows]

        bands = []
        for row in case_rows:
            low_si, unit_si = to_si(row["low"], row["unit"], row["metric"])
            high_si, _ = to_si(row["high"], row["unit"], row["metric"])
            bands.append(
                {
                    "metric": row["metric"],
                    "band_low_si": low_si,
                    "band_high_si": high_si,
                    "unit_si": unit_si,
                    "recorded_low": row["low"],
                    "recorded_high": row["high"],
                    "recorded_unit": row["unit"],
                    "band_kind": BAND_KIND,
                    "band_source": (
                        "tests/validation/hvac_equipment_rated_performance/data/"
                        "comparative_bounds_ce100_ce200.csv -- " + csv_source
                    ),
                    "provenance": {
                        "source_program": row["source_program"],
                        "program_version": row["program_version"],
                        "source_table": row["source_table"],
                        "source_page": row["source_page"],
                        "status": row["status"],
                    },
                }
            )

        missing_metrics = [m for m in metric_vocabulary if m not in present_metrics]
        if not bands:
            comparative_note = (
                "no comparative band recorded: this case has no transcribed row in "
                "tests/validation/hvac_equipment_rated_performance/data/"
                "comparative_bounds_ce100_ce200.csv (that file covers "
                + ", ".join(covered_cases)
                + "). No band is invented and no flat percentage is applied."
            )
        else:
            comparative_note = None

        # Metrics the transcribed file records somewhere, but not on this case:
        # stated explicitly per metric, naming the missing source, rather than
        # left as a silent omission. Whether the Task-22 publication itself
        # reports such a metric for this case is not established here.
        missing_metric_notes = [
            {
                "metric": metric,
                "comparative_note": (
                    "no transcribed band for metric '"
                    + metric
                    + "' on this case: the bounds file "
                    "tests/validation/hvac_equipment_rated_performance/data/"
                    "comparative_bounds_ce100_ce200.csv records no row for '"
                    + metric
                    + "' on "
                    + case_id
                    + " (it records "
                    + ", ".join(present_metrics)
                    + " for this case). Whether the Task-22 publication itself "
                    "reports that metric for this case is not established here: the "
                    "absence is a gap in the transcribed file in this repository, "
                    "and no band is invented for it."
                ),
            }
            for metric in missing_metrics
        ]

        # Cross-check the Task-22 identifier against the one the §9a table
        # already records in the band's source string (where a band exists).
        t22 = task22_case_id(case_id)
        ce_comparative = (ce.get("acceptance") or {}).get("comparative") or {}
        ce_source = ce_comparative.get("source", "")
        if ce_source and f"task-22 identifier {t22}" not in ce_source:
            raise ValueError(
                f"{case_id}: §9a table records a different Task-22 identifier "
                f"than the documented CE->E rename ({t22})"
            )

        cases.append(
            {
                "case_id": case_id,
                "case_name": ce.get("name"),
                "series": ce.get("series"),
                "source_case_reference": {
                    "standard_140_case_id": case_id,
                    "iea_shc_task22_case_id": t22,
                    "note": (
                        "IEA SHC Task 22 published this case as "
                        + t22
                        + "; ASHRAE 140-2023 renamed the family to CE100-CE200 "
                        "(same cases, new names -- #4296)."
                    ),
                },
                "case_definition_source": (
                    "data/reference/ashrae140/section9_ce_cases.json (generated by "
                    "scripts/generate_section9_ce_cases.py, Issue #4296)"
                ),
                "bands": bands,
                "comparative_note": comparative_note,
                "missing_metric_notes": missing_metric_notes,
                "comparative_series_status": (
                    "not implemented -- the ASHRAE 140-2023 Section 9.3 comparative "
                    "test series is not implemented in this tree; this row pairs the "
                    "case with its transcribed Task-22 evidence range only and "
                    "carries no engine value and no verdict."
                ),
            }
        )

    return {
        "_purpose": (
            "Machine-readable ASHRAE 140-2023 Section 9b comparative case table: "
            "one row per CE100-CE200 space-cooling equipment case, each carrying "
            "its transcribed IEA SHC Task 22 comparative evidence band(s) or an "
            "explicit missing-band note. GENERATED by "
            "scripts/generate_section9b_cases.py - do not hand-edit; regenerate. "
            "Issue #4273."
        ),
        "_scope": (
            "The ASHRAE 140-2023 Section 9.3 comparative test series is not "
            "implemented in this tree. This table scores the CE cases against "
            "transcribed Task-22 evidence ranges only, in the sense that it "
            "attaches the published range to each case: it does not run the "
            "comparative test series, it does not score an engine output, and it "
            "derives no verdict. Standard 140 defines no pass/fail criterion for "
            "these ranges."
        ),
        "_band_kind": BAND_KIND,
        "_no_pass_fail_criterion": (
            "Standard 140 defines no pass/fail criterion for the Task-22 "
            "comparative ranges. Every band in this table is labelled '"
            + BAND_KIND
            + "'. No band is fitted to fluxion's output, widened, interpolated "
            "between cases, or replaced by a flat percentage across cases."
        ),
        "_units": {
            "recorded": "MWh (energy), kW (power), C (temperature), as recorded in the bounds CSV",
            "si": "J (energy), W (power), K (temperature)",
            "normalisation": (
                "The SI endpoints use exactly the conversions the Rust loader "
                "applies (tests/validation/hvac_equipment_rated_performance/"
                "reference_data.rs, to_si): MWh -> J x 1.0e6 x 3600.0, "
                "kW -> W x 1.0e3, C -> K + 273.15. Both the recorded and the SI "
                "value/unit are emitted."
            ),
        },
        "_sources": {
            "bounds_csv": {
                "path": (
                    "tests/validation/hvac_equipment_rated_performance/data/"
                    "comparative_bounds_ce100_ce200.csv"
                ),
                "sha256": bounds_sha,
                "header_source_verbatim": csv_source,
                "cases_covered": covered_cases,
                "metric_vocabulary": metric_vocabulary,
            },
            "publication": publication,
            "publication_manifest": {
                "path": (
                    "tests/validation/hvac_equipment_rated_performance/data/"
                    "manifest.json"
                ),
                "sha256": manifest_sha,
            },
            "ce_case_table": {
                "path": "data/reference/ashrae140/section9_ce_cases.json",
                "sha256": ce_table_sha,
                "generated_by": "scripts/generate_section9_ce_cases.py",
                "issue": "#4296",
            },
        },
        "cases": cases,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed JSON is stale")
    args = ap.parse_args()

    doc = build()
    text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(
                f"STALE: {OUTPUT} does not match the generator; rerun without --check",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {OUTPUT} up to date ({len(doc['cases'])} cases)")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT} ({len(doc['cases'])} cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
